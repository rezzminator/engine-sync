// pluginHome is fixture's home with the Claude plugin flights enabled from a
// directory marketplace under {home}/market and listed in machine.plugins.
func pluginHome(t *testing.T) (home, repo string) {
	t.Helper()
	home, repo = fixture(t)
	claude := filepath.Join(home, ".claude")
	root := filepath.Join(home, "market", "plugins", "flights")
	for path, body := range map[string]string{
		filepath.Join(claude, "engine-sync.json"):                           `{"version":1,"machine":{"sourceGeneratedAgentsDir":"generated/agents","plugins":["flights"]}}`,
		filepath.Join(claude, "settings.json"):                              `{"enabledPlugins":{"flights@team-market":true}}`,
		filepath.Join(claude, "plugins", "known_marketplaces.json"):         `{"team-market":{"source":{"source":"directory","path":"{home}/market"},"installLocation":"{home}/market"}}`,
		filepath.Join(home, "market", ".claude-plugin", "marketplace.json"): `{"name":"team-market","plugins":[{"name":"flights","source":"./plugins/flights"}]}`,
		filepath.Join(root, "agents", "lander.md"):                          "---\nname: lander\ndescription: Land what flights:foreman built.\n---\nSpawn `flights:foreman`, never flights:foreman-x.\nRun python3 ${CLAUDE_PLUGIN_ROOT}/skills/inventory/inventory.py.\n",
		filepath.Join(root, "agents", "foreman.md"):                         "---\ndescription: Build.\n---\nBuild; hand to flights:lander.\n",
		filepath.Join(root, "commands", "doctor.md"):                        "---\ndescription: Meter.\n---\nAsk flights:lander, read ${CLAUDE_PLUGIN_ROOT}/x.\n",
		filepath.Join(root, "skills", "inventory", "SKILL.md"):              "---\nname: inventory\ndescription: Count.\n---\nRun ${CLAUDE_PLUGIN_ROOT}/skills/inventory/inventory.py for flights:lander.\n",
		filepath.Join(root, "skills", "inventory", "inventory.py"):          "print(1)\n",
		filepath.Join(claude, "commands", "tidy.md"):                        "---\ndescription: Tidy.\n---\nTidy up; then /flights:doctor.\n",
		filepath.Join(repo, "agents", "gamma.md"):                           "---\nname: gamma\ndescription: Gamma role.\nmodel: sonnet\neffort: medium\n---\n\nGamma body; call flights:lander.\n",
	} {
		writeMachineFixture(t, path, strings.ReplaceAll(body, "{home}", home))
	}
	return home, repo
}

// TestPluginTwinsCompileForCodexAndOpenCode: a machine.plugins plugin's
// agents, commands and skills land as Codex and OpenCode twins named
// "{plugin}-{name}", every body carries the agent roster and the resolved
// root, and Claude gets no link (it loads plugin agents itself).
func TestPluginTwinsCompileForCodexAndOpenCode(t *testing.T) {
	home, repo := pluginHome(t)
	root := filepath.Join(home, "market", "plugins", "flights")
	report := RunMachine(Options{Home: home, SourceRepo: repo, CodexHomes: []string{filepath.Join(home, ".codex")}})
	if report.Err != nil {
		t.Fatalf("err=%v events=%#v", report.Err, report.Events)
	}
	if got := messages(report.Events, VerbConflict); len(got) != 0 {
		t.Fatalf("conflicts %q, want none", got)
	}
	// Five Codex roles, and Claude links only the two machine agents.
	if got, want := messages(report.Events, VerbOK), []string{"Codex global agents compiled=5 linked=2", "Codex global commands wrote=6 unchanged=0 deleted=0"}; len(got) < 2 || !reflect.DeepEqual(got[:2], want) {
		t.Fatalf("ok events %q, want first %q", got, want)
	}
	want := map[string]string{
		".codex/agents/flights-lander.toml": "# Generated by engine-sync from plugin:flights/agents/lander.md — edit the source, then run: engine-sync global\n" +
			"name = \"flights-lander\"\ndescription = \"Land what flights-foreman built.\"\ndeveloper_instructions = \"\"\"\n" +
			"Spawn `flights-foreman`, never flights:foreman-x.\nRun python3 {root}/skills/inventory/inventory.py.\n\"\"\"\n",
		".codex/agents/flights-foreman.toml": "# Generated by engine-sync from plugin:flights/agents/foreman.md — edit the source, then run: engine-sync global\n" +
			"name = \"flights-foreman\"\ndescription = \"Build.\"\ndeveloper_instructions = \"\"\"\nBuild; hand to flights-lander.\n\"\"\"\n",
		".codex/agents/gamma.toml": "# Generated by engine-sync from agents/gamma.md — edit the source, then run: engine-sync global\n" +
			"name = \"gamma\"\ndescription = \"Gamma role.\"\nmodel_reasoning_effort = \"medium\"\ndeveloper_instructions = \"\"\"\nGamma body; call flights-lander.\n\"\"\"\n",
		".codex/prompts/tidy.md": "---\n# Generated by engine-sync from $HOME/.claude/commands/tidy.md — edit the source, then run: engine-sync build\n" +
			"name: tidy\ndescription: Tidy.\n---\nTidy up; then $flights-doctor.\n",
		".config/opencode/command/tidy.md": "---\n# Generated by engine-sync from $HOME/.claude/commands/tidy.md — edit the source, then run: engine-sync build\n" +
			"description: \"Tidy.\"\n---\nTidy up; then /flights-doctor.\n",
		".codex/prompts/flights-doctor.md": "---\n# Generated by engine-sync from plugin:flights/commands/doctor.md — edit the source, then run: engine-sync build\n" +
			"name: flights-doctor\ndescription: Meter.\n---\nAsk flights-lander, read {root}/x.\n",
		".codex/skills/flights-inventory/SKILL.md": "---\n# Generated by engine-sync from plugin:flights/skills/inventory/SKILL.md — edit the source, then run: engine-sync build\n" +
			"name: flights-inventory\ndescription: Count.\n---\nRun {root}/skills/inventory/inventory.py for flights-lander.\n",
		".codex/skills/flights-inventory/inventory.py": "-> {root}/skills/inventory/inventory.py",
		".config/opencode/agents/flights-lander.md": "---\n# Generated by engine-sync from plugin:flights/agents/lander.md — edit the source, then run: engine-sync global\n" +
			"description: \"Land what flights-foreman built.\"\nmode: all\n---\nSpawn `flights-foreman`, never flights:foreman-x.\nRun python3 {root}/skills/inventory/inventory.py.\n",
		".config/opencode/command/flights-doctor.md": "---\n# Generated by engine-sync from plugin:flights/commands/doctor.md — edit the source, then run: engine-sync build\n" +
			"description: \"Meter.\"\n---\nAsk flights-lander, read {root}/x.\n",
		".config/opencode/command/flights-inventory.md": "---\n# Generated by engine-sync from plugin:flights/skills/inventory/SKILL.md — edit the source, then run: engine-sync build\n" +
			"description: \"Count.\"\n---\nRun {root}/skills/inventory/inventory.py for flights-lander.\n",
	}
	files := tree(t, home)
	for rel, body := range want {
		path := filepath.Join(home, rel)
		if got, expected := files[path], strings.ReplaceAll(body, "{root}", root); got != expected {
			t.Fatalf("%s\n got %q\nwant %q", path, got, expected)
		}
	}
	if got := files[filepath.Join(home, ".claude", "agents", "gamma.md")]; got != "-> "+filepath.Join(repo, "agents", "gamma.md") {
		t.Fatalf("machine agent Claude link = %q", got)
	}
	for _, name := range []string{"flights-lander.md", "flights-foreman.md", "lander.md"} {
		if _, err := os.Lstat(filepath.Join(home, ".claude", "agents", name)); !errors.Is(err, fs.ErrNotExist) {
			t.Fatalf("plugin agent got a Claude-side %s: %v", name, err)
		}
	}
}

// TestPluginTwinsCompileWithNoMachineAgentsSource: with machine.plugins set,
// an absent machine agents directory still compiles every plugin agent.
func TestPluginTwinsCompileWithNoMachineAgentsSource(t *testing.T) {
	home, repo := pluginHome(t)
	if err := os.RemoveAll(filepath.Join(repo, "agents")); err != nil {
		t.Fatal(err)
	}
	report := RunMachine(Options{Home: home, SourceRepo: repo, CodexHomes: []string{filepath.Join(home, ".codex")}})
	if report.Err != nil {
		t.Fatalf("err=%v events=%#v", report.Err, report.Events)
	}
	path := filepath.Join(home, ".codex", "agents", "flights-foreman.toml")
	want := "# Generated by engine-sync from plugin:flights/agents/foreman.md — edit the source, then run: engine-sync global\n" +
		"name = \"flights-foreman\"\ndescription = \"Build.\"\ndeveloper_instructions = \"\"\"\nBuild; hand to flights-lander.\n\"\"\"\n"
	if got := tree(t, home)[path]; got != want {
		t.Fatalf("%s\n got %q\nwant %q", path, got, want)
	}
}

// TestPluginTwinFailuresAreNamed: a plugin twin that takes a machine twin's
// name and a plugin whose records cannot be read are each a named conflict;
// the unreadable plugin keeps its installed twins instead of retiring them.
func TestPluginTwinFailuresAreNamed(t *testing.T) {
	t.Run("collision with a machine agent", func(t *testing.T) {
		home, repo := pluginHome(t)
		writeMachineFixture(t, filepath.Join(repo, "agents", "flights-foreman.md"), "---\nname: flights-foreman\ndescription: Machine.\n---\nMachine.\n")
		report := RunMachine(Options{Home: home, SourceRepo: repo, CodexHomes: []string{filepath.Join(home, ".codex")}})
		want := []string{"plugin flights: agent flights-foreman from " + filepath.Join(home, "market", "plugins", "flights", "agents", "foreman.md") +
			" has the twin name of the machine agent " + filepath.Join(repo, "agents", "flights-foreman.md") + "; the machine agent keeps it, the plugin agent is skipped"}
		if got := messages(report.Events, VerbConflict); !reflect.DeepEqual(got, want) {
			t.Fatalf("conflicts\n got %q\nwant %q", got, want)
		}
	})
	t.Run("unreadable record keeps the installed twins", func(t *testing.T) {
		home, repo := pluginHome(t)
		codex := filepath.Join(home, ".codex")
		if report := RunMachine(Options{Home: home, SourceRepo: repo, CodexHomes: []string{codex}}); report.Err != nil {
			t.Fatalf("first build: %v", report.Err)
		}
		before := tree(t, home)
		known := filepath.Join(home, ".claude", "plugins", "known_marketplaces.json")
		writeMachineFixture(t, known, `{"team-market":`)
		report := RunMachine(Options{Home: home, SourceRepo: repo, CodexHomes: []string{codex}})
		problem := "plugin flights: could not resolve flights@team-market in " + filepath.Join(home, ".claude") + ": parse " + known + ": unexpected end of JSON input; its twins are kept"
		if report.Err == nil || !strings.Contains(report.Err.Error(), problem) {
			t.Fatalf("err = %v, want one naming %q", report.Err, problem)
		}
		for _, rel := range []string{".codex/agents/gamma.toml", ".codex/prompts/tidy.md", ".config/opencode/agents/gamma.md", ".config/opencode/command/tidy.md", ".codex/agents/flights-lander.toml", ".codex/skills/flights-inventory/SKILL.md", ".config/opencode/agents/flights-lander.md", ".config/opencode/command/flights-doctor.md"} {
			path := filepath.Join(home, rel)
			if got, err := os.ReadFile(path); err != nil || string(got) != before[path] {
				t.Fatalf("%s changed under an unreadable record: %q err=%v, want %q", path, got, err, before[path])
			}
		}
	})
}

// TestMachineDoctorCountsPluginTwins: the Codex registry row names plugin
// twins beside machine ones; the Claude store row never names them.
func TestMachineDoctorCountsPluginTwins(t *testing.T) {
	home, repo := pluginHome(t)
	options := DoctorOptions{Home: home, SourceRepo: repo}
	rows := func() []Row {
		got := []Row{}
		for _, status := range InspectRegistries(options) {
			got = append(got, Row{status.Level(), "global-agents " + status.Describe()})
		}
		return got
	}
	want := []Row{
		{LevelFail, "global-agents store dir=" + filepath.Join(home, ".claude") + ` state=MISSING names=gamma,gamma-deep hint="run engine-sync global"`},
		{LevelFail, "global-agents source=" + filepath.Join(home, ".codex", "agents") + ` state=MISSING names=gamma,gamma-deep,flights-foreman,flights-lander hint="run engine-sync global"`},
	}
	if got := rows(); !reflect.DeepEqual(got, want) {
		t.Fatalf("before install\n got %#v\nwant %#v", got, want)
	}
	if report := RunMachine(Options{Home: home, SourceRepo: repo}); report.Err != nil {
		t.Fatal(report.Err)
	}
	want = []Row{
		{LevelOK, "global-agents store dir=" + filepath.Join(home, ".claude") + " state=linked"},
		{LevelOK, "global-agents source=" + filepath.Join(home, ".codex", "agents") + " state=installed"},
	}
	if got := rows(); !reflect.DeepEqual(got, want) {
		t.Fatalf("after install\n got %#v\nwant %#v", got, want)
	}
	cfg, err := config.LoadConfigLayers("", home)
	if err != nil {
		t.Fatal(err)
	}
	states, err := AgentStates(home, repo, &cfg, nil, nil)
	if err != nil {
		t.Fatalf("AgentStates: %v", err)
	}
	claude, codex, opencode := filepath.Join(home, ".claude", "agents"), filepath.Join(home, ".codex", "agents"), filepath.Join(home, ".config", "opencode", "agents")
	wantStates := []AgentState{
		{Engine: EngineClaude, Name: "gamma", Path: filepath.Join(claude, "gamma.md"), State: StateInstalled},
		{Engine: EngineCodex, Name: "gamma", Path: filepath.Join(codex, "gamma.toml"), State: StateInstalled},
		{Engine: EngineClaude, Name: "gamma-deep", Path: filepath.Join(claude, "gamma-deep.md"), State: StateInstalled},
		{Engine: EngineCodex, Name: "gamma-deep", Path: filepath.Join(codex, "gamma-deep.toml"), State: StateInstalled},
		{Engine: EngineCodex, Name: "flights-foreman", Path: filepath.Join(codex, "flights-foreman.toml"), State: StateInstalled},
		{Engine: EngineCodex, Name: "flights-lander", Path: filepath.Join(codex, "flights-lander.toml"), State: StateInstalled},
		{Engine: EngineOpenCode, Name: "gamma", Path: filepath.Join(opencode, "gamma.md"), State: StateInstalled},
		{Engine: EngineOpenCode, Name: "gamma-deep", Path: filepath.Join(opencode, "gamma-deep.md"), State: StateInstalled},
		{Engine: EngineOpenCode, Name: "flights-foreman", Path: filepath.Join(opencode, "flights-foreman.md"), State: StateInstalled},
		{Engine: EngineOpenCode, Name: "flights-lander", Path: filepath.Join(opencode, "flights-lander.md"), State: StateInstalled},
	}
	if !reflect.DeepEqual(states, wantStates) {
		t.Fatalf("agent states\n got %+v\nwant %+v", states, wantStates)
	}
	known := filepath.Join(home, ".claude", "plugins", "known_marketplaces.json")
	writeMachineFixture(t, known, `{"team-market":`)
	want = []Row{
		{LevelFail, "global-agents source=" + filepath.Join(repo, "agents") + " state=BROKEN names=plugin:flights error=plugin flights: could not resolve flights@team-market in " + filepath.Join(home, ".claude") + ": parse " + known + `: unexpected end of JSON input note="engine-sync global skips each named agent and keeps its installed copies" hint="fix the named sources"`},
		{LevelOK, "global-agents store dir=" + filepath.Join(home, ".claude") + " state=linked"},
		{LevelOK, "global-agents source=" + filepath.Join(home, ".codex", "agents") + " state=installed"},
	}
	if got := rows(); !reflect.DeepEqual(got, want) {
		t.Fatalf("unreadable record\n got %#v\nwant %#v", got, want)
	}
}
