const generatedRole = "# Generated by pfm codex build from agents/old.md; do not edit\nname = \"old\"\n"

func writeMachineFixture(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

// fixture is one home with a clone holding a single global agent and one
// declared variant of it, and one Claude command to mirror.
func fixture(t *testing.T) (home, repo string) {
	t.Helper()
	home = testjail.Scratch(t)
	t.Setenv("XDG_CONFIG_HOME", filepath.Join(home, ".config"))
	repo = filepath.Join(home, "clone")
	agents := filepath.Join(repo, "agents")
	writeMachineFixture(t, filepath.Join(agents, "gamma.md"), "---\nname: gamma\ndescription: Gamma role.\nmodel: sonnet\neffort: medium\n---\n\nGamma body.\n")
	writeMachineFixture(t, filepath.Join(agents, source.GlobalAgentVariantsFile), `{"version":2,"variants":{"gamma-deep":{"from":"gamma","set":{"effort":"high"}}}}`)
	writeMachineFixture(t, filepath.Join(home, ".claude", "commands", "tidy.md"), "---\ndescription: Tidy.\n---\nTidy up.\n")
	writeMachineFixture(t, filepath.Join(home, ".config", "engine-sync", "config.json"), `{"version":1,"machine":{"retiredAgents":["frr","rr-super"],"retiredFiles":[".codex/agents/explorer.toml"]}}`)
	return home, repo
}

// tree lists every path under root with its kind and, for a file, its bytes,
// so a plan can be proven to have written nothing.
func tree(t *testing.T, root string) map[string]string {
	t.Helper()
	out := map[string]string{}
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		info, err := os.Lstat(path)
		if err != nil {
			return err
		}
		switch {
		case info.Mode()&os.ModeSymlink != 0:
			target, err := os.Readlink(path)
			if err != nil {
				return err
			}
			out[path] = "-> " + target
		case info.Mode().IsRegular():
			raw, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			out[path] = string(raw)
		default:
			out[path] = "dir"
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func messages(events []Event, verb string) []string {
	var out []string
	for _, event := range events {
		if event.Verb == verb {
			out = append(out, event.Message)
		}
	}
	return out
}

func TestRetirementsKeepWhatEngineSyncCannotProveItWrote(t *testing.T) {
	cases := []struct {
		name      string
		stage     func(t *testing.T, home string)
		retired   []string
		preserved []string
		skips     []string
	}{
		{
			name: "renamed role generated is retired, a foreign one of that name is preserved",
			stage: func(t *testing.T, home string) {
				writeMachineFixture(t, filepath.Join(home, ".codex", "agents", "frr.toml"), generatedRole)
				writeMachineFixture(t, filepath.Join(home, ".codex", "agents", "rr-super.toml"), "name = \"rr-super\"\n")
			},
			retired:   []string{".codex/agents/frr.toml"},
			preserved: []string{".codex/agents/rr-super.toml"},
			skips:     []string{".codex/agents/rr-super.toml is not a generated agent; preserved"},
		},
		{
			name: "an undeclared rendered variant and its link go",
			stage: func(t *testing.T, home string) {
				ghost := filepath.Join(paths.GeneratedClaudeAgentsDir(home), "ghost.md")
				writeMachineFixture(t, ghost, "---\nname: ghost\n---\n")
				if err := os.MkdirAll(filepath.Join(home, ".claude", "agents"), 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink(ghost, filepath.Join(home, ".claude", "agents", "ghost.md")); err != nil {
					t.Fatal(err)
				}
			},
			preserved: []string{".claude/agents/ghost.md", ".local/state/engine-sync/generated/claude-agents/ghost.md"},
		},
		{
			name: "the retired explorer role and its backups go",
			stage: func(t *testing.T, home string) {
				writeMachineFixture(t, filepath.Join(home, ".codex", "agents", "explorer.toml"), "name = \"explorer\"\n")
				writeMachineFixture(t, filepath.Join(home, ".codex", "agents", "explorer.toml.bak-1"), "old\n")
			},
			preserved: []string{".codex/agents/explorer.toml", ".codex/agents/explorer.toml.bak-1"},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			home, repo := fixture(t)
			tc.stage(t, home)
			report := RunMachine(Options{Home: home, SourceRepo: repo})
			if report.Err != nil {
				t.Fatalf("err=%v events=%#v", report.Err, report.Events)
			}
			var retired []string
			for _, event := range report.Events {
				if event.Verb == VerbRetire {
					retired = append(retired, strings.TrimPrefix(event.Path, home+"/"))
				}
			}
			sort.Strings(retired)
			if !reflect.DeepEqual(retired, tc.retired) {
				t.Fatalf("retired %q, want %q", retired, tc.retired)
			}
			for _, path := range tc.retired {
				if _, err := os.Lstat(filepath.Join(home, path)); !errors.Is(err, fs.ErrNotExist) {
					t.Fatalf("%s survived its retire: %v", path, err)
				}
			}
			for _, path := range tc.preserved {
				if _, err := os.Lstat(filepath.Join(home, path)); err != nil {
					t.Fatalf("%s was not preserved: %v", path, err)
				}
			}
			for _, skip := range tc.skips {
				want := filepath.Join(home, skip)
				found := false
				for _, got := range messages(report.Events, VerbSkip) {
					found = found || got == want
				}
				if !found {
					t.Fatalf("no skip %q in %q", want, messages(report.Events, VerbSkip))
				}
			}
		})
	}
}

func TestNoCodexHomeWritesNoRoleAndSkipsTheMirrors(t *testing.T) {
	home, repo := fixture(t)
	report := RunMachine(Options{Home: home, SourceRepo: repo, CodexHomes: []string{}})
	if report.Err != nil {
		t.Fatal(report.Err)
	}
	// OpenCode's global agents are no Codex home's: they are still written,
	// and the fixture's unmapped OpenCode aliases still warn.
	want := []string{
		`unmapped OpenCode model alias "sonnet" in ` + filepath.Join(repo, "agents", "gamma.md") + " — model omitted",
		`unmapped OpenCode model alias "sonnet" in ` + filepath.Join(paths.GeneratedClaudeAgentsDir(home), "gamma-deep.md") + " — model omitted",
		"no Codex accounts configured — command mirror has nothing to write",
		"no Codex accounts configured — agent mirror has nothing to write",
	}
	if got := messages(report.Events, VerbSkip); !reflect.DeepEqual(got, want) {
		t.Fatalf("skips %q, want %q", got, want)
	}
	if _, err := os.Lstat(filepath.Join(home, ".codex")); !errors.Is(err, fs.ErrNotExist) {
		t.Fatalf("a Codex home was written with none configured: %v", err)
	}
	if _, err := os.Readlink(filepath.Join(home, ".claude", "agents", "gamma.md")); err != nil {
		t.Fatalf("the Claude link is owed whatever the Codex roster: %v", err)
	}
}

// TestNoCodexHomeKeepsClaudeLinkOwnership: with no Codex home, the Claude
// registry links keep the same claim test as with one — a foreign link into
// another .claude/agents stays, a relative link into the generated store is ours.
func TestNoCodexHomeKeepsClaudeLinkOwnership(t *testing.T) {
	home, repo := fixture(t)
	registry := filepath.Join(home, ".claude", "agents")
	foreign := filepath.Join(home, "elsewhere", ".claude", "agents", "gamma.md")
	writeMachineFixture(t, foreign, "---\nname: gamma\ndescription: Theirs.\n---\n")
	store := filepath.Join(home, paths.ClaudeVariantStore, "gamma-deep.md")
	relative, err := filepath.Rel(registry, store)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(registry, 0o755); err != nil {
		t.Fatal(err)
	}
	for link, target := range map[string]string{"gamma.md": foreign, "gamma-deep.md": relative} {
		if err := os.Symlink(target, filepath.Join(registry, link)); err != nil {
			t.Fatal(err)
		}
	}
	RunMachine(Options{Home: home, SourceRepo: repo, CodexHomes: []string{}})
	if got, _ := os.Readlink(filepath.Join(registry, "gamma.md")); got != foreign {
		t.Fatalf("foreign Claude link was claimed: now -> %q", got)
	}
	if got, _ := os.Readlink(filepath.Join(registry, "gamma-deep.md")); got != relative {
		t.Fatalf("owned relative Claude link was refused: now -> %q, want %q", got, store)
	}
}

