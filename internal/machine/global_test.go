func TestACommandConflictBlocksButThePlanStillLists(t *testing.T) {
	home, repo := fixture(t)
	clean := RunMachine(Options{Home: home, SourceRepo: repo, Plan: true})
	var target string
	for _, message := range messages(clean.Events, VerbChange) {
		if strings.Contains(message, filepath.Join(home, ".codex")) && strings.Contains(message, "tidy") {
			target = strings.Fields(message)[1]
		}
	}
	if target == "" {
		t.Fatalf("the plan lists no tidy command mirror: %q", messages(clean.Events, VerbChange))
	}
	writeMachineFixture(t, target, "a hand-written file\n")
	for _, plan := range []bool{true, false} {
		report := RunMachine(Options{Home: home, SourceRepo: repo, Plan: plan})
		// A plan's conflict is a finding the caller turns into a plan error,
		// never a failure that stopped the run; the apply stops at it.
		if report.OK || (report.Err == nil) == !plan || len(messages(report.Events, VerbConflict)) == 0 {
			t.Fatalf("plan=%v: ok=%v err=%v conflicts=%q", plan, report.OK, report.Err, messages(report.Events, VerbConflict))
		}
		if raw, err := os.ReadFile(target); err != nil || string(raw) != "a hand-written file\n" {
			t.Fatalf("plan=%v: the foreign file was touched: %q %v", plan, raw, err)
		}
	}
}

func TestUninstallRetiresOnlyWhatIsGenerated(t *testing.T) {
	home, repo := fixture(t)
	if report := RunMachine(Options{Home: home, SourceRepo: repo}); report.Err != nil {
		t.Fatal(report.Err)
	}
	writeMachineFixture(t, filepath.Join(home, ".codex", "agents", "mine.toml"), "name = \"mine\"\n")
	legacy := paths.LegacyGeneratedCodexAgentsDir(home)
	writeMachineFixture(t, filepath.Join(legacy, "gamma.toml"), generatedRole)
	report := RunMachine(Options{Home: home, SourceRepo: repo, Uninstall: true})
	if report.Err != nil {
		t.Fatalf("err=%v events=%#v", report.Err, report.Events)
	}
	for _, gone := range []string{
		filepath.Join(home, ".codex", "agents", "gamma.toml"), legacy, paths.GeneratedClaudeAgentsDir(home),
	} {
		if _, err := os.Lstat(gone); !errors.Is(err, fs.ErrNotExist) {
			t.Fatalf("%s survived uninstall: %v", gone, err)
		}
	}
	if _, err := os.Stat(filepath.Join(home, ".codex", "agents", "mine.toml")); err != nil {
		t.Fatalf("uninstall touched a foreign role: %v", err)
	}
	if got := messages(report.Events, VerbOK); len(got) != 1 || !strings.Contains(got[0], "deleted=") {
		t.Fatalf("uninstall ok lines %q", got)
	}
}

// An uninstall on a host whose roster lists no Codex home still retires the
// managed command mirror an earlier install wrote under {home}/.codex, as the
// installer's own uninstall did whatever the roster.
func TestUninstallWithAnEmptyRosterRetiresTheCommandMirror(t *testing.T) {
	home, repo := fixture(t)
	if report := RunMachine(Options{Home: home, SourceRepo: repo}); report.Err != nil {
		t.Fatal(report.Err)
	}
	mirrored := func() []string {
		var out []string
		for path := range tree(t, filepath.Join(home, ".codex")) {
			if strings.Contains(filepath.Base(path), "tidy") {
				out = append(out, path)
			}
		}
		return out
	}
	if len(mirrored()) == 0 {
		t.Fatal("the install mirrored no tidy command; the fixture proves nothing")
	}
	report := RunMachine(Options{Home: home, SourceRepo: repo, CodexHomes: []string{}, Uninstall: true})
	if report.Err != nil {
		t.Fatalf("err=%v events=%#v", report.Err, report.Events)
	}
	if left := mirrored(); len(left) != 0 {
		t.Fatalf("the managed command mirror survived uninstall: %q (events %#v)", left, report.Events)
	}
}
