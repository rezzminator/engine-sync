package artifact

import "strings"

const Prefix = "Generated by engine-sync from "

// MCPBegin preserves the unbranded fence syntax understood by released 0.1.0.
const MCPBegin = LegacyMCPScript
const PreviousMCP = "# BEGIN mcp_servers — generated by engine-sync from .mcp.json — edit the source, then run: engine-sync build"
const MCPEnd = "# END mcp_servers — generated"
const LegacyCodex = "Generated by pfm codex build"
const LegacyOpenCode = "Generated by pfm opencode build"
const LegacyVariant = "Generated by pfm from templates/global/agents/"
const LegacyCodexScript = "Generated by .claude/scripts/build-codex.mjs"
const LegacyOpenCodeScript = "Generated by .claude/scripts/build-opencode.mjs"
const LegacyMCP = "# BEGIN mcp_servers — generated by pfm codex build from .mcp.json; do not edit inside this fence"
const LegacyMCPScript = "# BEGIN mcp_servers — generated by .claude/scripts/build-codex.mjs from .mcp.json; do not edit inside this fence"
const PriorMCP = "# BEGIN mcp_servers — generated by engine-sync codex build from .mcp.json; do not edit inside this fence"

func Line(source string) string {
	return Prefix + source + " — edit the source, then run: engine-sync build"
}
func Marker(syntax Syntax, source string) string {
	line := Line(source)
	switch syntax {
	case Markdown:
		return "<!-- " + line + " -->"
	case JSONC:
		return "// " + line
	default:
		return "# " + line
	}
}

// Claims examines ownership headers only; body quotations cannot claim a file.
func Claims(header string) bool {
	first, rest, _ := strings.Cut(header, "\n")
	if strings.TrimSpace(first) == "---" {
		first, _, _ = strings.Cut(rest, "\n")
	}
	first = strings.TrimSpace(first)
	first = strings.TrimPrefix(first, "<!-- ")
	first = strings.TrimSuffix(first, " -->")
	first = strings.TrimPrefix(first, "# ")
	first = strings.TrimPrefix(first, "// ")
	if strings.HasPrefix(first, Prefix) {
		source, ok := strings.CutSuffix(strings.TrimPrefix(first, Prefix), " — edit the source, then run: engine-sync build")
		return ok && strings.TrimSpace(source) != ""
	}
	for _, marker := range Markers()[1:] {
		tail, ok := strings.CutPrefix(first, marker)
		if !ok {
			continue
		}
		if marker == LegacyVariant {
			if source, ok := strings.CutSuffix(tail, " — edit the source"); ok && strings.Contains(source, ".md + ") && !strings.HasSuffix(source, ".md + ") {
				return true
			}
			return strings.HasSuffix(tail, " — edit the source, then run: "+strings.Fields(LegacyCodex)[2]+" install --yes") && len(tail) > len(" — edit the source, then run: "+strings.Fields(LegacyCodex)[2]+" install --yes")
		}
		if strings.HasPrefix(tail, " from ") && (strings.Contains(tail, "; do not edit") || strings.Contains(tail, " — edit the source") || strings.Contains(tail, " — DO NOT EDIT")) {
			return true
		}
	}
	return false
}
func Markers() []string {
	return []string{Prefix, "Generated by engine-sync codex build", "Generated by engine-sync opencode build", LegacyCodex, LegacyOpenCode, LegacyVariant, LegacyCodexScript, LegacyOpenCodeScript}
}
func MCPBegins() []string { return []string{MCPBegin, PreviousMCP, PriorMCP, LegacyMCP} }
