package artifact

import (
	"regexp"
	"strings"
)

const Prefix = "Generated by engine-sync from "

// MCPBegin opens the MCP fence engine-sync writes. Released 0.1.0 knows only
// LegacyMCPScript and reports this fence as an unpaired END conflict.
const MCPBegin = "# BEGIN mcp_servers — generated by engine-sync from .mcp.json — edit the source, then run: engine-sync build"
const MCPEnd = "# END mcp_servers — generated"
const LegacyCodexScript = "Generated by .claude/scripts/build-codex.mjs"
const LegacyOpenCodeScript = "Generated by .claude/scripts/build-opencode.mjs"

// LegacyMCPScript is the fence releases 0.1.0 to 0.5.0 wrote; live configs carry it.
const LegacyMCPScript = "# BEGIN mcp_servers — generated by .claude/scripts/build-codex.mjs from .mcp.json; do not edit inside this fence"
const PriorMCP = "# BEGIN mcp_servers — generated by engine-sync codex build from .mcp.json; do not edit inside this fence"

// RulesBegin and RulesEnd fence the global always-on rules block engine-sync
// owns inside a Codex home's AGENTS.md; text outside the fence is never its.
const RulesBegin = "<!-- BEGIN engine-sync rules — owned -->"
const RulesEnd = "<!-- END engine-sync rules — owned -->"

// buildSuffix and globalSuffix end a marker line with the command that
// rewrites the file: build for a project mirror, global for a machine render.
const (
	buildSuffix  = " — edit the source, then run: engine-sync build"
	globalSuffix = " — edit the source, then run: engine-sync global"
)

func Line(source string) string {
	return Prefix + source + buildSuffix
}
func Marker(syntax Syntax, source string) string {
	return wrap(syntax, Line(source))
}

// GlobalMarker marks a machine-scope render, which engine-sync global writes.
func GlobalMarker(syntax Syntax, source string) string {
	return wrap(syntax, Prefix+source+globalSuffix)
}

func wrap(syntax Syntax, line string) string {
	switch syntax {
	case Markdown:
		return "<!-- " + line + " -->"
	case JSONC:
		return "// " + line
	default:
		return "# " + line
	}
}

// Claims examines ownership headers only; body quotations cannot claim a file.
func Claims(header string) bool {
	first, rest, _ := strings.Cut(header, "\n")
	if strings.TrimSpace(first) == "---" {
		first, _, _ = strings.Cut(rest, "\n")
	}
	first = strings.TrimSpace(first)
	first = strings.TrimPrefix(first, "<!-- ")
	first = strings.TrimSuffix(first, " -->")
	first = strings.TrimPrefix(first, "# ")
	first = strings.TrimPrefix(first, "// ")
	if strings.HasPrefix(first, Prefix) {
		rest := strings.TrimPrefix(first, Prefix)
		source, ok := strings.CutSuffix(rest, buildSuffix)
		if !ok {
			source, ok = strings.CutSuffix(rest, globalSuffix)
		}
		return ok && strings.TrimSpace(source) != ""
	}
	for _, marker := range Markers()[1:] {
		tail, ok := strings.CutPrefix(first, marker)
		if !ok {
			continue
		}
		if strings.HasPrefix(tail, " from ") && (strings.Contains(tail, "; do not edit") || strings.Contains(tail, " — edit the source") || strings.Contains(tail, " — DO NOT EDIT")) {
			return true
		}
	}
	return false
}
func Markers() []string {
	return []string{Prefix, "Generated by engine-sync codex build", "Generated by engine-sync opencode build", LegacyCodexScript, LegacyOpenCodeScript}
}
func MCPBegins() []string { return []string{MCPBegin, PriorMCP, LegacyMCPScript} }

// ManagedByPattern is the shape of a managed-by value: the installer's name.
const ManagedByPattern = `^[a-z][a-z0-9-]{0,31}$`

var managedByValue = regexp.MustCompile(ManagedByPattern)

const managedByKey = "managed-by: "

// ManagedByLine wraps `managed-by: {value}` in a file's comment syntax.
func ManagedByLine(syntax Syntax, value string) string {
	return wrap(syntax, managedByKey+value)
}

// headerEnd is the byte offset just past the generated header line of text,
// which follows the opening `---` of a front-matter file; -1 when the first
// line (after that fence) is not a claimed header.
func headerEnd(text string) int {
	start := 0
	if first, _, _ := strings.Cut(text, "\n"); strings.TrimSpace(first) == "---" {
		start = len(first) + 1
	}
	if start > len(text) {
		return -1
	}
	line, _, found := strings.Cut(text[start:], "\n")
	if !found || !Claims(text[start:]) {
		return -1
	}
	return start + len(line) + 1
}

// ManagedBy reads the installer's name from the line after the generated
// header of a claimed file; a body quotation never counts.
func ManagedBy(header string) (string, bool) {
	end := headerEnd(header)
	if end < 0 {
		return "", false
	}
	line, _, _ := strings.Cut(header[end:], "\n")
	line = strings.TrimSpace(line)
	line = strings.TrimPrefix(line, "<!-- ")
	line = strings.TrimSuffix(line, " -->")
	line = strings.TrimPrefix(line, "# ")
	line = strings.TrimPrefix(line, "// ")
	value, ok := strings.CutPrefix(line, managedByKey)
	if !ok || !managedByValue.MatchString(value) {
		return "", false
	}
	return value, true
}

// WithManagedBy inserts the managed-by line directly after the generated
// header of content, in the header's own comment syntax; an empty value, or
// content with no claimed header, is returned as it is.
func WithManagedBy(content string, value string) string {
	end := headerEnd(content)
	if value == "" || end < 0 {
		return content
	}
	header := strings.TrimRight(content[:end], "\n")
	header = header[strings.LastIndex(header, "\n")+1:]
	syntax := TOML
	switch {
	case strings.HasPrefix(header, "<!-- "):
		syntax = Markdown
	case strings.HasPrefix(header, "// "):
		syntax = JSONC
	}
	return content[:end] + ManagedByLine(syntax, value) + "\n" + content[end:]
}
