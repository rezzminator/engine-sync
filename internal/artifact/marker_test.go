func TestManagedByLineFollowsTheGeneratedHeader(t *testing.T) {
	const value = "installer"
	cases := []struct {
		name   string
		syntax Syntax
		file   string
		want   string
	}{
		{"toml", TOML, GlobalMarker(TOML, "agents/a.md") + "\nname = \"a\"\n", GlobalMarker(TOML, "agents/a.md") + "\n# managed-by: installer\nname = \"a\"\n"},
		{"yaml front", YAMLFront, "---\n" + GlobalMarker(YAMLFront, "agents/a.md") + "\nmode: subagent\n---\nbody\n", "---\n" + GlobalMarker(YAMLFront, "agents/a.md") + "\n# managed-by: installer\nmode: subagent\n---\nbody\n"},
		{"markdown", Markdown, GlobalMarker(Markdown, "c.md") + "\nbody\n", GlobalMarker(Markdown, "c.md") + "\n<!-- managed-by: installer -->\nbody\n"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := WithManagedBy(c.file, value); got != c.want {
				t.Fatalf("WithManagedBy:\n%q\nwant\n%q", got, c.want)
			}
			if got, ok := ManagedBy(c.want); !ok || got != value {
				t.Fatalf("ManagedBy = %q, %v; want %q", got, ok, value)
			}
			if _, ok := ManagedBy(c.file); ok {
				t.Fatal("a file without the line read as managed")
			}
			if got := WithManagedBy(c.file, ""); got != c.file {
				t.Fatalf("an empty value changed the file: %q", got)
			}
			if !Claims(c.want) {
				t.Fatal("the managed-by line broke the ownership claim")
			}
		})
	}
	if got := ManagedByLine(TOML, value); got != "# managed-by: installer" {
		t.Fatal(got)
	}
	if got := ManagedByLine(JSONC, value); got != "// managed-by: installer" {
		t.Fatal(got)
	}
}

func TestManagedByReadsOnlyTheLineAfterTheHeader(t *testing.T) {
	header := GlobalMarker(TOML, "agents/a.md")
	for name, text := range map[string]string{
		"body quote":    header + "\nname = \"a\"\n# managed-by: installer\n",
		"unclaimed":     "# managed-by: installer\n# other\n",
		"bad value":     header + "\n# managed-by: Pro fessor\n",
		"empty value":   header + "\n# managed-by: \n",
		"user file":     "# Generated by engine-sync from forged\n# managed-by: installer\n",
		"header absent": "",
	} {
		if got, ok := ManagedBy(text); ok {
			t.Errorf("%s: read %q", name, got)
		}
	}
}
