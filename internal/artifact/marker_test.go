package artifact

import (
	"strings"
	"testing"
)

func TestMarkerSyntaxAndLegacyClaims(t *testing.T) {
	for _, syntax := range []Syntax{Markdown, TOML, JSONC, YAMLFront} {
		for _, source := range []string{".claude/agents/reader.md", "CLAUDE.md", "nested/.claude/commands/review.md"} {
			if got := Marker(syntax, source); !Claims(got) || !strings.Contains(got, "engine-sync build") {
				t.Fatal(got)
			}
		}
		got := Marker(syntax, ".claude/agents/reader.md")
		for _, legacy := range []string{LegacyCodex, LegacyOpenCode, LegacyVariant, LegacyCodexScript, LegacyOpenCodeScript} {
			if strings.Contains(got, legacy) {
				t.Fatal(got)
			}
		}
	}
	for _, legacy := range []string{LegacyCodex, LegacyOpenCode, LegacyCodexScript, LegacyOpenCodeScript} {
		if !Claims("# " + legacy + " from source; do not edit") {
			t.Fatal(legacy)
		}
	}
	if Claims("# User file\n" + Marker(TOML, "source")) {
		t.Fatal("a body quote claimed the file")
	}
}

func TestReviewOwnershipRequiresCompleteMarker(t *testing.T) {
	for _, text := range []string{"# Generated by engine-sync from forged", "# Generated by pfm codex build — what I learned"} {
		if Claims(text) {
			t.Errorf("claimed user prose: %q", text)
		}
	}
}

func TestReviewReleasedVariantHeader(t *testing.T) {
	header := "# " + LegacyVariant + "reader.md + variants.json — edit the source"
	if !Claims(header) {
		t.Fatal("complete released variant ownership lost")
	}
	if Claims("# " + LegacyVariant + "reader.md") {
		t.Fatal("partial header claimed")
	}
}
