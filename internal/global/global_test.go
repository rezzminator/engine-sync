func TestACommandConflictBlocksButThePlanStillLists(t *testing.T) {
	home, repo := fixture(t)
	clean := Run(Options{Home: home, SourceRepo: repo, Plan: true})
	var target string
	for _, message := range messages(clean.Events, VerbChange) {
		if strings.Contains(message, filepath.Join(home, ".codex")) && strings.Contains(message, "tidy") {
			target = strings.Fields(message)[1]
		}
	}
	if target == "" {
		t.Fatalf("the plan lists no tidy command mirror: %q", messages(clean.Events, VerbChange))
	}
	write(t, target, "a hand-written file\n")
	for _, plan := range []bool{true, false} {
		report := Run(Options{Home: home, SourceRepo: repo, Plan: plan})
		// A plan's conflict is a finding the caller turns into a plan error,
		// never a failure that stopped the run; the apply stops at it.
		if report.OK || (report.Err == nil) == !plan || len(messages(report.Events, VerbConflict)) == 0 {
			t.Fatalf("plan=%v: ok=%v err=%v conflicts=%q", plan, report.OK, report.Err, messages(report.Events, VerbConflict))
		}
		if raw, err := os.ReadFile(target); err != nil || string(raw) != "a hand-written file\n" {
			t.Fatalf("plan=%v: the foreign file was touched: %q %v", plan, raw, err)
		}
	}
}

func TestUninstallRetiresOnlyWhatIsGenerated(t *testing.T) {
	home, repo := fixture(t)
	if report := Run(Options{Home: home, SourceRepo: repo}); report.Err != nil {
		t.Fatal(report.Err)
	}
	write(t, filepath.Join(home, ".codex", "agents", "mine.toml"), "name = \"mine\"\n")
	legacy := paths.LegacyGeneratedCodexAgentsDir(home)
	write(t, filepath.Join(legacy, "gamma.toml"), generatedRole)
	report := Run(Options{Home: home, SourceRepo: repo, Uninstall: true})
	if report.Err != nil {
		t.Fatalf("err=%v events=%#v", report.Err, report.Events)
	}
	for _, gone := range []string{
		filepath.Join(home, ".codex", "agents", "gamma.toml"), legacy, paths.GeneratedClaudeAgentsDir(home),
	} {
		if _, err := os.Lstat(gone); !errors.Is(err, fs.ErrNotExist) {
			t.Fatalf("%s survived uninstall: %v", gone, err)
		}
	}
	if _, err := os.Stat(filepath.Join(home, ".codex", "agents", "mine.toml")); err != nil {
		t.Fatalf("uninstall touched a foreign role: %v", err)
	}
	if got := messages(report.Events, VerbOK); len(got) != 1 || !strings.Contains(got[0], "deleted=") {
		t.Fatalf("uninstall ok lines %q", got)
	}
}

// An uninstall on a host whose roster lists no Codex home still retires the
// managed command mirror an earlier install wrote under {home}/.codex, as the
// installer's own uninstall did whatever the roster.
func TestUninstallWithAnEmptyRosterRetiresTheCommandMirror(t *testing.T) {
	home, repo := fixture(t)
	if report := Run(Options{Home: home, SourceRepo: repo}); report.Err != nil {
		t.Fatal(report.Err)
	}
	mirrored := func() []string {
		var out []string
		for path := range tree(t, filepath.Join(home, ".codex")) {
			if strings.Contains(filepath.Base(path), "tidy") {
				out = append(out, path)
			}
		}
		return out
	}
	if len(mirrored()) == 0 {
		t.Fatal("the install mirrored no tidy command; the fixture proves nothing")
	}
	report := Run(Options{Home: home, SourceRepo: repo, CodexHomes: []string{}, Uninstall: true})
	if report.Err != nil {
		t.Fatalf("err=%v events=%#v", report.Err, report.Events)
	}
	if left := mirrored(); len(left) != 0 {
		t.Fatalf("the managed command mirror survived uninstall: %q (events %#v)", left, report.Events)
	}
}

func TestMachineDoctorRows(t *testing.T) {
	home, repo := fixture(t)
	cases := []struct {
		name    string
		options DoctorOptions
		stage   func(t *testing.T)
		want    []Row
	}{
		{
			name:    "no clone is named, not warned",
			options: DoctorOptions{Home: home},
			want: []Row{{LevelOK, "global-agents source=" + filepath.Join(home, ".professor") + " state=NO-CLONE" +
				` note="no Professor clone recorded or at the default path — global agents install from a clone (INSTALL.md § Build from source)"`}},
		},
		{
			name:    "claude absent names the store",
			options: DoctorOptions{Home: home, SourceRepo: repo, ClaudeAbsent: true},
			want: []Row{{LevelOK, "global-agents store dir=" + filepath.Join(home, ".claude") + " state=NO-CLAUDE" +
				` note="no Claude Code binary installed — the installer never wires the store's agents"`}},
		},
		{
			name:    "nothing installed fails both registries",
			options: DoctorOptions{Home: home, SourceRepo: repo},
			want: []Row{
				{LevelFail, "global-agents store dir=" + filepath.Join(home, ".claude") + ` state=MISSING names=gamma,gamma-deep hint="run pfm install"`},
				{LevelFail, "global-agents source=" + filepath.Join(home, ".codex", "agents") + ` state=MISSING names=gamma,gamma-deep hint="run pfm install"`},
			},
		},
		{
			name:    "an applied install is clean",
			options: DoctorOptions{Home: home, SourceRepo: repo},
			stage: func(t *testing.T) {
				if report := Run(Options{Home: home, SourceRepo: repo}); report.Err != nil {
					t.Fatal(report.Err)
				}
			},
			want: []Row{
				{LevelOK, "global-agents store dir=" + filepath.Join(home, ".claude") + " state=linked"},
				{LevelOK, "global-agents source=" + filepath.Join(home, ".codex", "agents") + " state=installed"},
			},
		},
		{
			name:    "a drifted role is a mismatch",
			options: DoctorOptions{Home: home, SourceRepo: repo},
			stage: func(t *testing.T) {
				write(t, filepath.Join(home, ".codex", "agents", "gamma.toml"), generatedRole)
			},
			want: []Row{
				{LevelOK, "global-agents store dir=" + filepath.Join(home, ".claude") + " state=linked"},
				{LevelFail, "global-agents source=" + filepath.Join(home, ".codex", "agents") + ` state=MISMATCH names=gamma hint="run pfm install"`},
			},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if tc.stage != nil {
				tc.stage(t)
			}
			if got := Doctor(tc.options); !reflect.DeepEqual(got, tc.want) {
				t.Fatalf("rows\n got %#v\nwant %#v", got, tc.want)
			}
		})
	}
}
