const generatedRole = "# Generated by pfm codex build from templates/global/agents/old.md; do not edit\nname = \"old\"\n"

func write(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

// fixture is one home with a clone holding a single global agent and one
// declared variant of it, and one Claude command to mirror.
func fixture(t *testing.T) (home, repo string) {
	t.Helper()
	home = t.TempDir()
	repo = filepath.Join(home, "clone")
	agents := filepath.Join(repo, "templates", "global", "agents")
	write(t, filepath.Join(agents, "gamma.md"), "---\nname: gamma\ndescription: Gamma role.\nmodel: sonnet\neffort: medium\n---\n\nGamma body.\n")
	write(t, filepath.Join(agents, codexgen.GlobalAgentVariantsFile), `{"gamma-deep":{"from":"gamma","effort":"high"}}`)
	write(t, filepath.Join(home, ".claude", "commands", "tidy.md"), "---\ndescription: Tidy.\n---\nTidy up.\n")
	return home, repo
}

// tree lists every path under root with its kind and, for a file, its bytes,
// so a plan can be proven to have written nothing.
func tree(t *testing.T, root string) map[string]string {
	t.Helper()
	out := map[string]string{}
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		info, err := os.Lstat(path)
		if err != nil {
			return err
		}
		switch {
		case info.Mode()&os.ModeSymlink != 0:
			target, err := os.Readlink(path)
			if err != nil {
				return err
			}
			out[path] = "-> " + target
		case info.Mode().IsRegular():
			raw, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			out[path] = string(raw)
		default:
			out[path] = "dir"
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func messages(events []Event, verb string) []string {
	var out []string
	for _, event := range events {
		if event.Verb == verb {
			out = append(out, event.Message)
		}
	}
	return out
}

// The plan is the apply's preview: the same change and retire lines, nothing
// written by the plan, and the apply's result on disk.
func TestPlanListsExactlyWhatTheApplyDoes(t *testing.T) {
	home, repo := fixture(t)
	write(t, filepath.Join(home, ".codex", "agents", "old.toml"), generatedRole)
	write(t, filepath.Join(home, ".codex", "agents", "mine.toml"), "name = \"mine\"\n")
	options := Options{Home: home, SourceRepo: repo, Plan: true}
	before := tree(t, home)
	plan := Run(options)
	if plan.Err != nil || !plan.OK {
		t.Fatalf("plan err=%v ok=%v events=%#v", plan.Err, plan.OK, plan.Events)
	}
	if after := tree(t, home); !reflect.DeepEqual(before, after) {
		t.Fatalf("the plan wrote to disk")
	}
	options.Plan = false
	apply := Run(options)
	if apply.Err != nil || !apply.OK {
		t.Fatalf("apply err=%v events=%#v", apply.Err, apply.Events)
	}
	for _, verb := range []string{VerbChange, VerbRetire} {
		if got, want := messages(apply.Events, verb), messages(plan.Events, verb); !reflect.DeepEqual(got, want) {
			t.Fatalf("%s lines differ:\nplan  %q\napply %q", verb, want, got)
		}
	}
	role := filepath.Join(home, ".codex", "agents", "gamma.toml")
	raw, err := os.ReadFile(role)
	if err != nil || !codexgen.GeneratedGlobalRole(raw) {
		t.Fatalf("role %s = %q, %v; want a generated role file", role, raw, err)
	}
	link := filepath.Join(home, ".claude", "agents", "gamma.md")
	if target, err := os.Readlink(link); err != nil || target != filepath.Join(repo, "templates", "global", "agents", "gamma.md") {
		t.Fatalf("claude link %s -> %q, %v", link, target, err)
	}
	variant := filepath.Join(paths.GeneratedClaudeAgentsDir(home), "gamma-deep.md")
	if _, err := os.Stat(variant); err != nil {
		t.Fatalf("rendered variant %s: %v", variant, err)
	}
	if _, err := os.Lstat(filepath.Join(home, ".codex", "agents", "old.toml")); !errors.Is(err, fs.ErrNotExist) {
		t.Fatalf("orphaned generated role survived: %v", err)
	}
	if _, err := os.Stat(filepath.Join(home, ".codex", "agents", "mine.toml")); err != nil {
		t.Fatalf("a foreign role was touched: %v", err)
	}
	if got := messages(apply.Events, VerbOK); len(got) != 2 ||
		!strings.HasPrefix(got[0], "Codex global agents compiled=") ||
		!strings.HasPrefix(got[1], "Codex global commands wrote=") {
		t.Fatalf("ok lines = %q", got)
	}
	if again := Run(options); len(messages(again.Events, VerbChange)) != 0 || len(messages(again.Events, VerbRetire)) != 0 {
		t.Fatalf("a second apply changed something: %#v", again.Events)
	}
}

func TestRetirementsKeepWhatEngineSyncCannotProveItWrote(t *testing.T) {
	cases := []struct {
		name      string
		stage     func(t *testing.T, home string)
		retired   []string
		preserved []string
		skips     []string
	}{
		{
			name: "renamed role generated is retired, a foreign one of that name is preserved",
			stage: func(t *testing.T, home string) {
				write(t, filepath.Join(home, ".codex", "agents", "frr.toml"), generatedRole)
				write(t, filepath.Join(home, ".codex", "agents", "rr-super.toml"), "name = \"rr-super\"\n")
			},
			retired:   []string{".codex/agents/frr.toml"},
			preserved: []string{".codex/agents/rr-super.toml"},
			skips:     []string{".codex/agents/rr-super.toml is not a generated agent; preserved"},
		},
		{
			name: "an undeclared rendered variant and its link go",
			stage: func(t *testing.T, home string) {
				ghost := filepath.Join(paths.GeneratedClaudeAgentsDir(home), "ghost.md")
				write(t, ghost, "---\nname: ghost\n---\n")
				if err := os.MkdirAll(filepath.Join(home, ".claude", "agents"), 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink(ghost, filepath.Join(home, ".claude", "agents", "ghost.md")); err != nil {
					t.Fatal(err)
				}
			},
			retired: []string{".claude/agents/ghost.md", ".local/state/pfm/generated/claude-agents/ghost.md"},
		},
		{
			name: "the retired explorer role and its backups go",
			stage: func(t *testing.T, home string) {
				write(t, filepath.Join(home, ".codex", "agents", "explorer.toml"), "name = \"explorer\"\n")
				write(t, filepath.Join(home, ".codex", "agents", "explorer.toml.bak-1"), "old\n")
			},
			retired: []string{".codex/agents/explorer.toml", ".codex/agents/explorer.toml.bak-1"},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			home, repo := fixture(t)
			tc.stage(t, home)
			report := Run(Options{Home: home, SourceRepo: repo})
			if report.Err != nil {
				t.Fatalf("err=%v events=%#v", report.Err, report.Events)
			}
			var retired []string
			for _, event := range report.Events {
				if event.Verb == VerbRetire {
					retired = append(retired, strings.TrimPrefix(event.Path, home+"/"))
				}
			}
			sort.Strings(retired)
			if !reflect.DeepEqual(retired, tc.retired) {
				t.Fatalf("retired %q, want %q", retired, tc.retired)
			}
			for _, path := range tc.retired {
				if _, err := os.Lstat(filepath.Join(home, path)); !errors.Is(err, fs.ErrNotExist) {
					t.Fatalf("%s survived its retire: %v", path, err)
				}
			}
			for _, path := range tc.preserved {
				if _, err := os.Lstat(filepath.Join(home, path)); err != nil {
					t.Fatalf("%s was not preserved: %v", path, err)
				}
			}
			for _, skip := range tc.skips {
				want := filepath.Join(home, skip)
				found := false
				for _, got := range messages(report.Events, VerbSkip) {
					found = found || got == want
				}
				if !found {
					t.Fatalf("no skip %q in %q", want, messages(report.Events, VerbSkip))
				}
			}
		})
	}
}

