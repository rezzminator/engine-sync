const rulesHeader = "<!-- Generated by engine-sync from CLAUDE.md — edit the source, then run: engine-sync build -->\n"

// projectRulesFixture is a root with an always-on rule naming a command and a
// model alias, a path-scoped rule, a visible-to rule and a child project with
// a rule of its own; the root adapter is set so the rules' place before it
// shows.
func projectRulesFixture(t *testing.T) (root, home string) {
	t.Helper()
	root, home = testjail.Scratch(t), testjail.Scratch(t)
	writeCodexFixture(t, filepath.Join(root, ".claude", "engine-sync.json"), `{"version":1,"codex":{"globalCommands":false,"modelMap":{"sonnet":"gpt-5"},"rootAdapter":"\nAdapter.\n"}}`)
	writeCodexFixture(t, filepath.Join(root, "CLAUDE.md"), "# Fixture\n")
	writeCodexFixture(t, filepath.Join(root, ".claude", "commands", "tidy.md"), "---\ndescription: Tidy.\n---\nTidy up.\n")
	rules := filepath.Join(root, ".claude", "rules")
	writeCodexFixture(t, filepath.Join(rules, "always.md"), "---\ndescription: ignored\n---\nRun /tidy with model: sonnet; see CLAUDE.md.\n")
	writeCodexFixture(t, filepath.Join(rules, "scoped.md"), "---\npaths: [\"api/**/*.go\", \"cmd/**\"]\n---\nNo hardcoded locations.\n")
	writeCodexFixture(t, filepath.Join(rules, "sub", "visible.md"), "---\nvisible-to: [main]\n---\nMain only on Claude.\n")
	writeCodexFixture(t, filepath.Join(root, "app", "CLAUDE.md"), "# App\n")
	writeCodexFixture(t, filepath.Join(root, "app", ".claude", "rules", "child.md"), "Child rule.\n")
	return root, home
}

const wantRootAGENTS = rulesHeader + "# Fixture\n\n" +
	"<!-- rule: .claude/rules/always.md -->\nRun $tidy with model: gpt-5; see AGENTS.md.\n\n" +
	"<!-- rule: .claude/rules/scoped.md (path-scoped) -->\n" +
	"Before working on a file matching `api/**/*.go`, `cmd/**`, read .claude/rules/scoped.md and follow it.\n\n" +
	"<!-- rule: .claude/rules/sub/visible.md -->\nMain only on Claude.\n" +
	"\nAdapter.\n"

const wantAppAGENTS = "<!-- Generated by engine-sync from app/CLAUDE.md — edit the source, then run: engine-sync build -->\n" +
	"# App\n\n<!-- rule: app/.claude/rules/child.md -->\nChild rule.\n"

func TestProjectRulesCompileIntoAGENTS(t *testing.T) {
	root, home := projectRulesFixture(t)
	if result, err := Build(Options{Root: root, Home: home}); err != nil || !result.OK {
		t.Fatalf("build: result=%#v err=%v", result, err)
	}
	for path, want := range map[string]string{filepath.Join(root, "AGENTS.md"): wantRootAGENTS, filepath.Join(root, "app", "AGENTS.md"): wantAppAGENTS} {
		if got := string(readCodexFixture(t, path)); got != want {
			t.Fatalf("%s:\n%s\nwant:\n%s", path, got, want)
		}
	}

	writeCodexFixture(t, filepath.Join(root, ".claude", "rules", "always.md"), "Edited.\n")
	before := snapshotTestTree(t, root, home)
	result, err := CheckProject(Options{Root: root, Home: home})
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	if want := []string{"STALE " + filepath.Join(root, "AGENTS.md")}; result.OK || !sameRows(result.Problems, want) {
		t.Fatalf("check after a rule edit: OK=%v problems=%q, want %q", result.OK, result.Problems, want)
	}
	if after := snapshotTestTree(t, root, home); after != before {
		t.Fatalf("check changed files:\nbefore=%s\nafter=%s", before, after)
	}
	if result, err := Build(Options{Root: root, Home: home}); err != nil || !result.OK {
		t.Fatalf("rebuild: result=%#v err=%v", result, err)
	}
	if result, err := CheckProject(Options{Root: root, Home: home}); err != nil || !result.OK {
		t.Fatalf("check after the rebuild: result=%#v err=%v", result, err)
	}
	assertCodexContains(t, filepath.Join(root, "AGENTS.md"), "<!-- rule: .claude/rules/always.md -->\nEdited.\n\n")
}

// A rule whose header does not parse blocks its project's AGENTS.md, named,
// never compiled without it.
func TestProjectRuleWithBrokenFrontmatterIsAProblem(t *testing.T) {
	root, home := testjail.Scratch(t), testjail.Scratch(t)
	writeCodexFixture(t, filepath.Join(root, "CLAUDE.md"), "# Fixture\n")
	broken := filepath.Join(root, ".claude", "rules", "broken.md")
	writeCodexFixture(t, broken, "---\npaths:\n  - a: [unclosed\n---\nBody.\n")
	writeCodexFixture(t, filepath.Join(root, ".claude", "agents", "clerk.md"), "---\ndescription: Clerk.\n---\nClerk.\n")
	result, err := Build(Options{Root: root, Home: home})
	if err != nil {
		t.Fatalf("build: %v", err)
	}
	prefix := "RULE-FRONTMATTER " + broken + ": "
	if result.OK || len(result.Problems) != 1 || !strings.HasPrefix(result.Problems[0], prefix) {
		t.Fatalf("build: OK=%v problems=%q, want one starting %q", result.OK, result.Problems, prefix)
	}
	if _, err := os.Stat(filepath.Join(root, "AGENTS.md")); !os.IsNotExist(err) {
		t.Fatalf("AGENTS.md was written past a broken rule: %v", err)
	}
}

// sameRows compares report rows, nil and empty alike.
func sameRows(got, want []string) bool {
	return len(got) == len(want) && (len(got) == 0 || reflect.DeepEqual(got, want))
}

func containsPrefix(items []string, prefix string) bool {
	for _, item := range items {
		if strings.HasPrefix(item, prefix) {
			return true
		}
	}
	return false
}
