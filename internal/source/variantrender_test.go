const variantLead = "---\nname: lead\ndescription: Lead agent.\ntools: Read, Agent\nmodel: opus # tier note\nskills:\n  - one\n" +
	"engines:\n  codex:\n    effort: high\n---\n\nIntro line for lead.\n\n## Budget\n\n- at most 4\n\n## Procedure\n\n" +
	"1. Spawn lead-helper and lead.\n2. See ~/.claude/agents/lead.md and lead.md.\n3. Report to lead.\n\n" +
	"```text\n## Fenced\n```\n\n### Detail\n\nDetail text.\n\n## Twice\n\none\n\n## Twice\n\ntwo\n"

const variantLeadBody = "\nIntro line for lead.\n\n## Budget\n\n- at most 4\n\n## Procedure\n\n" +
	"1. Spawn lead-helper and lead.\n2. See ~/.claude/agents/lead.md and lead.md.\n3. Report to lead.\n\n" +
	"```text\n## Fenced\n```\n\n### Detail\n\nDetail text.\n\n## Twice\n\none\n\n## Twice\n\ntwo\n"

const variantMarker = "# Generated by engine-sync from agents/lead.md + variants.json — edit the source, then run: engine-sync build\n"

func variantPin(extent string) string {
	sum := sha256.Sum256([]byte(extent))
	return "sha256:" + hex.EncodeToString(sum[:])
}

// TestVariantsV2Render drives R2 through LoadGlobalAgentVariants: each case
// declares variants.json beside lead.md and asserts one variant's rendered
// file exactly, or the error the load returns.
func TestVariantsV2Render(t *testing.T) {
	budgetPin := variantPin("- at most 4")
	procedure := "1. Spawn lead-helper and lead.\n2. See ~/.claude/agents/lead.md and lead.md.\n3. Report to lead.\n\n" +
		"```text\n## Fenced\n```\n\n### Detail\n\nDetail text."
	for name, tc := range map[string]struct {
		decl, variant, want, err string
	}{
		"version 1 is retired": {
			decl: `{"lead-pro":{"from":"lead","effort":"medium"}}`,
			err:  "variants.json: version 1 is retired — rewrite as version 2 (see docs/interface.md)",
		},
		"unset set add and tools": {
			decl:    `{"version":2,"variants":{"lead-pro":{"from":"lead","unset":["skills"],"set":{"model":"sonnet","engines":{"codex":{"model":"gpt-x"}}},"add":{"tools":["Write"]}}}}`,
			variant: "lead-pro",
			want: "---\n" + variantMarker + "name: lead-pro\nrole: lead\ndescription: Lead agent.\ntools: Read, Agent, Write\nmodel: sonnet # tier note\n" +
				"engines:\n  codex:\n    effort: high\n    model: gpt-x\n---\n" + variantLeadBody,
		},
		"set tools list renders the comma form": {
			decl:    `{"version":2,"variants":{"lead-pro":{"from":"lead","set":{"tools":["Read","Grep"]}}}}`,
			variant: "lead-pro",
			want: "---\n" + variantMarker + "name: lead-pro\nrole: lead\ndescription: Lead agent.\ntools: Read, Grep\nmodel: opus # tier note\nskills:\n  - one\n" +
				"engines:\n  codex:\n    effort: high\n---\n" + variantLeadBody,
		},
		"unset of a missing key": {
			decl: `{"version":2,"variants":{"lead-pro":{"from":"lead","unset":["color"]}}}`,
			err:  `UNSET-MISSING lead-pro: lead.md has no frontmatter key "color"`,
		},
		"add to a scalar": {
			decl: `{"version":2,"variants":{"lead-pro":{"from":"lead","add":{"model":["x"]}}}}`,
			err:  "add.model: the frontmatter value is a scalar",
		},
		"name can never be set": {
			decl: `{"version":2,"variants":{"lead-pro":{"from":"lead","set":{"name":"x"}}}}`,
			err:  `"name" can never be set`,
		},
		"section override with its pin": {
			decl:    `{"version":2,"variants":{"lead-pro":{"from":"lead","sections":{"Budget":{"pin":"` + budgetPin + `","text":"- at most 9\n","heading":"Budget (pro)"}}}}}`,
			variant: "lead-pro",
			want: "---\n" + variantMarker + "name: lead-pro\nrole: lead\ndescription: Lead agent.\ntools: Read, Agent\nmodel: opus # tier note\nskills:\n  - one\n" +
				"engines:\n  codex:\n    effort: high\n---\n" + strings.Replace(variantLeadBody, "## Budget\n\n- at most 4\n", "## Budget (pro)\n\n- at most 9\n", 1),
		},
		"section extent runs over deeper headings": {
			decl:    `{"version":2,"variants":{"lead-pro":{"from":"lead","sections":{"Procedure":{"pin":"` + variantPin(procedure) + `","text":"Short."}}}}}`,
			variant: "lead-pro",
			want: "---\n" + variantMarker + "name: lead-pro\nrole: lead\ndescription: Lead agent.\ntools: Read, Agent\nmodel: opus # tier note\nskills:\n  - one\n" +
				"engines:\n  codex:\n    effort: high\n---\n\nIntro line for lead.\n\n## Budget\n\n- at most 4\n\n## Procedure\n\nShort.\n\n## Twice\n\none\n\n## Twice\n\ntwo\n",
		},
		"intro keeps the leading blank line": {
			decl:    `{"version":2,"variants":{"lead-pro":{"from":"lead","sections":{"(intro)":{"pin":"` + variantPin("Intro line for lead.") + `","text":"New intro."}}}}}`,
			variant: "lead-pro",
			want: "---\n" + variantMarker + "name: lead-pro\nrole: lead\ndescription: Lead agent.\ntools: Read, Agent\nmodel: opus # tier note\nskills:\n  - one\n" +
				"engines:\n  codex:\n    effort: high\n---\n" + strings.Replace(variantLeadBody, "Intro line for lead.", "New intro.", 1),
		},
		"last section keeps the final newline": {
			decl:    `{"version":2,"variants":{"lead-pro":{"from":"lead","sections":{"Detail":{"pin":"` + variantPin("Detail text.") + `","text":"More detail."}}}}}`,
			variant: "lead-pro",
			want: "---\n" + variantMarker + "name: lead-pro\nrole: lead\ndescription: Lead agent.\ntools: Read, Agent\nmodel: opus # tier note\nskills:\n  - one\n" +
				"engines:\n  codex:\n    effort: high\n---\n" + strings.Replace(variantLeadBody, "Detail text.", "More detail.", 1),
		},
		"drifted pin": {
			decl: `{"version":2,"variants":{"lead-pro":{"from":"lead","sections":{"Budget":{"pin":"sha256:00","text":"x"}}}}}`,
			err:  "SECTION-DRIFT lead-pro: lead.md § Budget changed since pinned (pin sha256:00, now " + budgetPin + ") — review the override, then run engine-sync variants pin lead-pro",
		},
		"missing section": {
			decl: `{"version":2,"variants":{"lead-pro":{"from":"lead","sections":{"Ghost":{"pin":"sha256:00","text":"x"}}}}}`,
			err:  `SECTION-MISSING lead-pro: lead.md has no section "Ghost"`,
		},
		"a heading inside a fence is no section": {
			decl: `{"version":2,"variants":{"lead-pro":{"from":"lead","sections":{"Fenced":{"pin":"sha256:00","text":"x"}}}}}`,
			err:  `SECTION-MISSING lead-pro: lead.md has no section "Fenced"`,
		},
		"a heading that occurs twice": {
			decl: `{"version":2,"variants":{"lead-pro":{"from":"lead","sections":{"Twice":{"pin":"sha256:00","text":"x"}}}}}`,
			err:  `SECTION-AMBIGUOUS lead-pro: lead.md has more than one section "Twice"`,
		},
		"an unpinned section": {
			decl: `{"version":2,"variants":{"lead-pro":{"from":"lead","sections":{"Budget":{"text":"x"}}}}}`,
			err:  "SECTION-UNPINNED lead-pro: lead.md § Budget has no pin — run engine-sync variants pin lead-pro",
		},
		"rename only standalone names": {
			decl:    `{"version":2,"variants":{"lead-pro":{"from":"lead","rename":{"lead":"chief"}}}}`,
			variant: "lead-pro",
			want: "---\n" + variantMarker + "name: lead-pro\nrole: lead\ndescription: Lead agent.\ntools: Read, Agent\nmodel: opus # tier note\nskills:\n  - one\n" +
				"engines:\n  codex:\n    effort: high\n---\n" + strings.NewReplacer("Intro line for lead.", "Intro line for chief.", "Spawn lead-helper and lead.", "Spawn lead-helper and chief.",
				"Report to lead.", "Report to chief.").Replace(variantLeadBody),
		},
		"renames are simultaneous": {
			decl:    `{"version":2,"variants":{"lead-pro":{"from":"lead","rename":{"lead":"lead-helper","lead-helper":"aide"}}}}`,
			variant: "lead-pro",
			want: "---\n" + variantMarker + "name: lead-pro\nrole: lead\ndescription: Lead agent.\ntools: Read, Agent\nmodel: opus # tier note\nskills:\n  - one\n" +
				"engines:\n  codex:\n    effort: high\n---\n" + strings.NewReplacer("Intro line for lead.", "Intro line for lead-helper.", "Spawn lead-helper and lead.", "Spawn aide and lead-helper.",
				"Report to lead.", "Report to lead-helper.").Replace(variantLeadBody),
		},
		"a rename count is taken from the original body": {
			decl: `{"version":2,"variants":{"lead-pro":{"from":"lead","rename":{"lead":"chief","chief":"boss"}}}}`,
			err:  "RENAME-UNUSED lead-pro: chief matched 0 times",
		},
		"rename that matches nothing": {
			decl: `{"version":2,"variants":{"lead-pro":{"from":"lead","rename":{"ghost":"x"}}}}`,
			err:  "RENAME-UNUSED lead-pro: ghost matched 0 times",
		},
		"general-purpose with profiles and fragments": {
			decl: `{"version":2,"fragments":{"law":"Law text."},"profiles":{"base":{"set":{"requires":["cap-x"]},"prepend":"@law"},` +
				`"worker":{"profile":"base","append":"Tail text."}},"variants":{"worker-one":{"from":"general-purpose","profile":"worker","set":{"description":"Worker."}}}}`,
			variant: "worker-one",
			want: "---\n# Generated by engine-sync from agents/variants.json — edit the source, then run: engine-sync build\n" +
				"name: worker-one\nrequires:\n  - cap-x\ndescription: Worker.\n---\nLaw text.\n\nTail text.",
		},
		"prepend and append around a body": {
			decl:    `{"version":2,"variants":{"lead-pro":{"from":"lead","prepend":"Before.","append":"After."}}}`,
			variant: "lead-pro",
			want: "---\n" + variantMarker + "name: lead-pro\nrole: lead\ndescription: Lead agent.\ntools: Read, Agent\nmodel: opus # tier note\nskills:\n  - one\n" +
				"engines:\n  codex:\n    effort: high\n---\nBefore.\n\n" + variantLeadBody + "\n\nAfter.",
		},
		"from a variant keeps the root role": {
			decl:    `{"version":2,"variants":{"lead-a":{"from":"lead","set":{"model":"sonnet"}},"lead-b":{"from":"lead-a","set":{"effort":"low"}}}}`,
			variant: "lead-b",
			want: "---\n" + variantMarker + "name: lead-b\nrole: lead\ndescription: Lead agent.\ntools: Read, Agent\nmodel: sonnet # tier note\nskills:\n  - one\n" +
				"engines:\n  codex:\n    effort: high\neffort: low\n---\n" + variantLeadBody,
		},
		"from cycle": {
			decl: `{"version":2,"variants":{"lead-a":{"from":"lead-b"},"lead-b":{"from":"lead-a"}}}`,
			err:  `"from" cycle lead-a → lead-b → lead-a`,
		},
		"profile cycle": {
			decl: `{"version":2,"profiles":{"p":{"profile":"q"},"q":{"profile":"p"}},"variants":{"lead-a":{"from":"lead","profile":"p"}}}`,
			err:  "profile cycle p → q → p",
		},
		"unknown profile": {
			decl: `{"version":2,"variants":{"lead-a":{"from":"lead","profile":"ghost"}}}`,
			err:  `unknown profile "ghost"`,
		},
		"profile carrying from": {
			decl: `{"version":2,"profiles":{"p":{"from":"lead"}},"variants":{}}`,
			err:  `profile "p": "from" belongs to a variant, never a profile`,
		},
		"unknown fragment": {
			decl: `{"version":2,"variants":{"lead-a":{"from":"lead","append":"@ghost"}}}`,
			err:  `names unknown fragment "@ghost"`,
		},
		"name collides with an original": {
			decl: `{"version":2,"variants":{"lead":{"from":"general-purpose"}}}`,
			err:  "collides with the original agent lead.md",
		},
		"name is not kebab-case": {
			decl: `{"version":2,"variants":{"Bad Name":{"from":"lead"}}}`,
			err:  `variant "Bad Name": name is not kebab-case`,
		},
		"unknown field": {
			decl: `{"version":2,"variants":{"lead-a":{"from":"lead","replace":{"a":"b"}}}}`,
			err:  `unknown field "replace"`,
		},
	} {
		t.Run(name, func(t *testing.T) {
			dir := filepath.Join(testjail.Scratch(t), "agents")
			if err := os.MkdirAll(dir, 0o755); err != nil {
				t.Fatal(err)
			}
			for file, content := range map[string]string{"lead.md": variantLead, GlobalAgentVariantsFile: tc.decl} {
				if err := os.WriteFile(filepath.Join(dir, file), []byte(content), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			variants, err := LoadGlobalAgentVariants(dir, filepath.Join(dir, "out"))
			if tc.err != "" {
				if err == nil || !strings.Contains(err.Error(), tc.err) {
					t.Fatalf("err = %v, want one containing %q", err, tc.err)
				}
				return
			}
			if err != nil {
				t.Fatalf("load: %v", err)
			}
			for _, v := range variants {
				if v.Name != tc.variant {
					continue
				}
				if got := string(v.Content); got != tc.want {
					t.Fatalf("rendered %s:\n%q\nwant:\n%q", v.Name, got, tc.want)
				}
				if v.Path != filepath.Join(dir, "out", v.Name+".md") {
					t.Fatalf("path = %s", v.Path)
				}
				return
			}
			t.Fatalf("no variant %q among %d rendered", tc.variant, len(variants))
		})
	}
}
