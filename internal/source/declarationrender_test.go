const leadSource = "---\nname: lead\ndescription: Lead agent.\ntools: Read, Agent\nmodel: opus # tier note\nskills:\n  - one\n" +
	"engines:\n  codex:\n    effort: high\n---\n\nIntro line for lead.\n\n## Budget\n\n- at most 4\n\n## Procedure\n\n" +
	"1. Spawn lead-helper and lead.\n2. See ~/.claude/agents/lead.md and lead.md.\n3. Report to lead.\n\n" +
	"```text\n## Fenced\n```\n\n### Detail\n\nDetail text.\n\n## Twice\n\none\n\n## Twice\n\ntwo\n"
const leadSourceBody = "\nIntro line for lead.\n\n## Budget\n\n- at most 4\n\n## Procedure\n\n" +
	"1. Spawn lead-helper and lead.\n2. See ~/.claude/agents/lead.md and lead.md.\n3. Report to lead.\n\n" +
	"```text\n## Fenced\n```\n\n### Detail\n\nDetail text.\n\n## Twice\n\none\n\n## Twice\n\ntwo\n"

func pinBlock(extent string) string {
	sum := sha256.Sum256([]byte(extent))
	return "sha256:" + hex.EncodeToString(sum[:])
}

// TestDeclarationRender exercises source-file declarations through the public loader.
func TestDeclarationRender(t *testing.T) {
	leadFront := "name: lead-pro\nrole: lead\ndescription: Lead agent.\ntools: Read, Agent\nmodel: opus # tier note\nskills:\n  - one\nengines:\n  codex:\n    effort: high\n"
	marker := "# Generated by engine-sync from agents/lead.md + lead-pro.md — edit the source, then run: engine-sync global\n"
	normal := "---\n" + marker + leadFront + "---\n" + leadSourceBody
	declaration := func(head, body string) string { return "---\nname: lead-pro\nfrom: lead\n" + head + "---\n" + body }
	budget := pinBlock("- at most 4")
	for name, tc := range map[string]struct {
		files                 map[string]string
		head, body, want, err string
	}{
		"native keys deep merge lists replace add comma tools": {
			head: "model: sonnet\nskills:\n  - two\nengines:\n  codex:\n    model: gpt-x\nadd:\n  tools: Write, Grep\n",
			want: "---\n" + marker + "name: lead-pro\nrole: lead\ndescription: Lead agent.\ntools: Read, Agent, Write, Grep\nmodel: sonnet # tier note\nskills:\n  - two\nengines:\n  codex:\n    effort: high\n    model: gpt-x\n---\n" + leadSourceBody,
		},
		"native YAML alias":            {head: "model: &tier sonnet\nengines:\n  codex:\n    model: *tier\n", want: strings.Replace(strings.Replace(normal, "model: opus", "model: sonnet", 1), "    effort: high\n---", "    effort: high\n    model: sonnet\n---", 1)},
		"merged declaration controls":  {files: map[string]string{"lead-pro.md": "---\n<<: {name: lead-pro, from: lead, model: sonnet}\n---\n"}, want: strings.Replace(normal, "model: opus", "model: sonnet", 1)},
		"duplicate native key":         {head: "model: sonnet\nmodel: haiku\n", err: "duplicate key model"},
		"cyclic YAML alias":            {head: "hooks: &hook [*hook]\n", err: "cyclic YAML alias"},
		"unset":                        {head: "unset: [skills]\n", want: strings.Replace(normal, "skills:\n  - one\n", "", 1)},
		"unset missing":                {head: "unset: [color]\n", err: "UNSET-MISSING lead-pro"},
		"add scalar":                   {head: "add:\n  model: [x]\n", err: "add.model: the frontmatter value is a scalar"},
		"retitle section":              {head: "retitle:\n  Budget: Budget (pro)\npins:\n  Budget: " + budget + "\n", body: "\n## Budget (pro)\n\n- at most 9\n", want: strings.Replace(normal, "## Budget\n\n- at most 4\n", "## Budget (pro)\n\n- at most 9\n", 1)},
		"intro keeps leading blank":    {head: "pins:\n  (intro): " + pinBlock("Intro line for lead.") + "\n", body: "\nNew intro.\n", want: strings.Replace(normal, "Intro line for lead.", "New intro.", 1)},
		"empty intro inherits":         {head: "pins:\n  Budget: " + budget + "\n", body: "\n\n## Budget\n\n- at most 9\n", want: strings.Replace(normal, "- at most 4", "- at most 9", 1)},
		"section missing":              {body: "\n## Ghost\n\nx\n", err: "SECTION-MISSING lead-pro"},
		"fenced heading is no section": {body: "\n## Fenced\n\nx\n", err: "SECTION-MISSING lead-pro"},
		"ambiguous section":            {body: "\n## Twice\n\nx\n", err: "SECTION-AMBIGUOUS lead-pro"},
		"unpinned":                     {body: "\n## Budget\n\nx\n", err: "SECTION-UNPINNED lead-pro"},
		"drift":                        {head: "pins:\n  Budget: sha256:00\n", body: "\n## Budget\n\nx\n", err: "SECTION-DRIFT lead-pro"},
		"rename simultaneous":          {head: "rename:\n  lead: lead-helper\n  lead-helper: aide\n", want: strings.NewReplacer("Intro line for lead.", "Intro line for lead-helper.", "Spawn lead-helper and lead.", "Spawn aide and lead-helper.", "Report to lead.", "Report to lead-helper.").Replace(normal)},
		"rename unused":                {head: "rename:\n  lead: chief\n  chief: boss\n", err: "RENAME-UNUSED lead-pro: chief matched 0 times"},
		"prepend append":               {head: "prepend: |-\n  Before.\nappend: |-\n  After.\n", want: "---\n" + marker + leadFront + "---\nBefore.\n\n" + leadSourceBody + "\n\nAfter."},
		"extends ordered nested": {head: "extends: [shared/a.md, shared/b.md]\neffort: low\n", files: map[string]string{
			"shared/root.md": "---\nmodel: sonnet\n---\n",
			"shared/a.md":    "---\nextends: [root.md]\neffort: high\n---\n",
			"shared/b.md":    "---\nmodel: haiku\n---\n",
		}, want: strings.Replace(strings.Replace(normal, "model: opus", "model: haiku", 1), "    effort: high\n---", "    effort: high\neffort: low\n---", 1)},
		"shared pinned body":          {head: "extends: [shared/lane.md]\n", files: map[string]string{"shared/lane.md": "---\npins:\n  Budget: " + budget + "\n---\n\n## Budget\n\n- at most 9\n"}, want: strings.Replace(normal, "- at most 4", "- at most 9", 1)},
		"extends missing":             {head: "extends: [shared/ghost.md]\n", err: "extends \"shared/ghost.md\": no shared file"},
		"extends a bare name":         {head: "extends: [lane]\n", err: "extends names a shared file by its relative path"},
		"extends an agent file":       {head: "extends: [lead.md]\n", err: "must name a shared file in a subdirectory"},
		"extends out of the tree":     {head: "extends: [../x/lane.md]\n", err: "must name a shared file in a subdirectory"},
		"extends cycle":               {head: "extends: [shared/a.md]\n", files: map[string]string{"shared/a.md": "---\nextends: [b.md]\n---\n", "shared/b.md": "---\nextends: [a.md]\n---\n"}, err: "extends cycle shared/a.md → shared/b.md → shared/a.md"},
		"shared file with a name":     {head: "extends: [shared/lane.md]\n", files: map[string]string{"shared/lane.md": "---\nname: lane\nmodel: haiku\n---\n"}, err: "a shared file is not an agent"},
		"shared file unused":          {files: map[string]string{"shared/lane.md": "---\nmodel: haiku\n---\n"}, err: "SHARED-UNUSED"},
		"abstract retired":            {files: map[string]string{"lane.md": "---\nname: lane\nabstract: true\n---\n"}, err: "abstract is retired"},
		"from chain":                  {files: map[string]string{"lead-pro.md": "---\nname: lead-pro\nfrom: lead-a\neffort: low\n---\n", "lead-a.md": "---\nname: lead-a\nfrom: lead\nmodel: sonnet\n---\n"}, want: strings.Replace(strings.Replace(normal, "model: opus", "model: sonnet", 1), "    effort: high\n---", "    effort: high\neffort: low\n---", 1)},
		"from cycle":                  {files: map[string]string{"lead-pro.md": "---\nname: lead-pro\nfrom: lead-a\n---\n", "lead-a.md": "---\nname: lead-a\nfrom: lead-pro\n---\n"}, err: "\"from\" cycle lead-a → lead-pro → lead-a"},
		"file name mismatch":          {files: map[string]string{"lead-pro.md": "---\nname: wrong\nfrom: lead\n---\n"}, err: "DECLARATION-INVALID"},
		"general purpose empty joins": {files: map[string]string{"lead-pro.md": "---\nname: lead-pro\nfrom: general-purpose\nprepend: |-\n  Law.\nappend: |-\n  Tail.\n---\n"}, want: "---\n# Generated by engine-sync from agents/lead-pro.md — edit the source, then run: engine-sync global\nname: lead-pro\n---\nLaw.\n\nTail."},
		"empty extended joins": {files: map[string]string{
			"lead-pro.md":     "---\nname: lead-pro\nfrom: general-purpose\nextends: [shared/blank.md]\nprepend: Law.\nappend: Tail.\n---\n",
			"shared/blank.md": "---\nprepend: ''\nappend: ''\n---\n",
		}, want: "---\n# Generated by engine-sync from agents/lead-pro.md — edit the source, then run: engine-sync global\nname: lead-pro\n---\nLaw.\n\nTail."},
		"general purpose empty parts": {files: map[string]string{"lead-pro.md": "---\nname: lead-pro\nfrom: general-purpose\nprepend: ''\nappend: |-\n  Tail.\n---\n"}, want: "---\n# Generated by engine-sync from agents/lead-pro.md — edit the source, then run: engine-sync global\nname: lead-pro\n---\nTail."},
	} {
		t.Run(name, func(t *testing.T) {
			dir := filepath.Join(testjail.Scratch(t), "agents")
			if err := os.MkdirAll(dir, 0o755); err != nil {
				t.Fatal(err)
			}
			files := map[string]string{"lead.md": leadSource, "lead-pro.md": declaration(tc.head, tc.body)}
			for file, content := range tc.files {
				files[file] = content
			}
			for file, content := range files {
				if err := os.MkdirAll(filepath.Dir(filepath.Join(dir, file)), 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(filepath.Join(dir, file), []byte(content), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			rendered, err := LoadDeclarations(dir, filepath.Join(dir, "out"))
			if tc.err != "" {
				if err == nil || !strings.Contains(err.Error(), tc.err) {
					t.Fatalf("err = %v, want %q", err, tc.err)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			for _, agent := range rendered {
				if agent.Name == "lead-pro" {
					if string(agent.Content) != tc.want {
						t.Fatalf("rendered %q, want %q", agent.Content, tc.want)
					}
					return
				}
			}
			t.Fatal("no rendered declaration lead-pro")
		})
	}
}
