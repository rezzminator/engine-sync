func TestMigrationClaimsBothEnginesAndMCPFence(t *testing.T) {
	root, home := testjail.Scratch(t), testjail.Scratch(t)
	putProjectFile(t, root, "CLAUDE.md", "# Sample\n")
	putProjectFile(t, root, ".mcp.json", `{"mcpServers":{"sample":{"command":"sample-server"}}}`)
	putProjectFile(t, root, ".claude/agents/reader.md", "---\nname: reader\ndescription: Reads.\n---\nRead.\n")
	putProjectFile(t, root, ".claude/commands/hello.md", "---\ndescription: Say hello.\n---\nHello.\n")
	e := env{get: func(key string) string {
		if key == "HOME" {
			return home
		}
		return ""
	}}
	var out, errOut bytes.Buffer
	if code := dispatch([]string{"build", root}, &out, &errOut, e); code != 0 {
		t.Fatalf("build rc=%d: %s%s", code, &out, &errOut)
	}
	if err := filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !entry.Type().IsRegular() {
			return nil
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		legacy := artifact.LegacyCodexScript
		if strings.Contains(path, ".opencode") {
			legacy = artifact.LegacyOpenCodeScript
		}
		old := bytes.ReplaceAll(raw, []byte(artifact.Prefix), []byte(legacy+" from "))
		old = bytes.ReplaceAll(old, []byte(artifact.MCPBegin), []byte(artifact.LegacyMCPScript))
		return os.WriteFile(path, old, 0644)
	}); err != nil {
		t.Fatal(err)
	}
	out.Reset()
	errOut.Reset()
	if code := dispatch([]string{"build", root}, &out, &errOut, e); code != 0 {
		t.Fatalf("migration build rc=%d: %s%s", code, &out, &errOut)
	}
	if code := dispatch([]string{"check", root}, &out, &errOut, e); code != 0 {
		t.Fatalf("migration check rc=%d: %s%s", code, &out, &errOut)
	}
	raw, err := os.ReadFile(filepath.Join(root, ".codex", "config.toml"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(raw), artifact.MCPBegin) || strings.Count(string(raw), "[mcp_servers.sample]") != 1 {
		t.Fatalf("migrated MCP fence: %s", raw)
	}
}

