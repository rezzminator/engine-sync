func TestMirrorsPreserveLinksToForeignClaudeRoots(t *testing.T) {
	root, home, outside := testjail.Scratch(t), testjail.Scratch(t), testjail.Scratch(t)
	putProjectFile(t, root, "CLAUDE.md", "# Sample\n")
	putProjectFile(t, outside, ".claude/skills/operator/SKILL.md", "Operator skill.\n")
	target := filepath.Join(outside, ".claude", "skills", "operator")
	for _, engine := range []string{"codex", "opencode"} {
		path := filepath.Join(root, "."+engine, "skills", "operator")
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink(target, path); err != nil {
			t.Fatal(err)
		}
	}
	e := env{get: func(key string) string {
		if key == "HOME" {
			return home
		}
		return ""
	}}
	var out, errOut bytes.Buffer
	if code := dispatch([]string{"build", root}, &out, &errOut, e); code != 0 {
		t.Fatalf("build rc=%d: %s%s", code, &out, &errOut)
	}
	for _, engine := range []string{"codex", "opencode"} {
		path := filepath.Join(root, "."+engine, "skills", "operator")
		if found, err := os.Readlink(path); err != nil || found != target {
			t.Errorf("foreign %s link=%q err=%v", engine, found, err)
		}
	}
}

func TestReviewPartialWriterRecorded(t *testing.T) {
	home, root := testjail.Scratch(t), testjail.Scratch(t)
	e := env{get: func(k string) string {
		if k == "HOME" {
			return home
		}
		return ""
	}}
	code, err := guarded(e, []string{root}, true, func() int {
		if e := os.WriteFile(filepath.Join(root, "written"), []byte("new"), 0600); e != nil {
			t.Fatal(e)
		}
		return 1
	})
	if code != 1 || err != nil {
		t.Fatalf("partial outcome %d %v", code, err)
	}
	if err := guard.Check(e.state(home), root, "0.1.0"); !errors.Is(err, guard.ErrNewerWriter) {
		t.Fatalf("partial writer unrecorded: %v", err)
	}
}
