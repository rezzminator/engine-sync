type goldenArtifact struct {
	Kind    string `json:"kind"`
	Content string `json:"content,omitempty"`
	Target  string `json:"target,omitempty"`
	Mode    uint32 `json:"mode,omitempty"`
}

func copyGoldenInput(t *testing.T, source, destination string) {
	t.Helper()
	if err := filepath.WalkDir(source, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(source, path)
		if err != nil {
			return err
		}
		target := filepath.Join(destination, rel)
		if entry.IsDir() {
			return os.MkdirAll(target, 0755)
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, raw, 0644)
	}); err != nil {
		t.Fatal(err)
	}
}

func collectGoldenArtifacts(t *testing.T, root, home string) map[string]goldenArtifact {
	t.Helper()
	artifacts := map[string]goldenArtifact{}
	for _, surface := range []struct{ label, root string }{{"project", root}, {"home", home}} {
		if err := filepath.WalkDir(surface.root, func(path string, entry fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			rel, err := filepath.Rel(surface.root, path)
			if err != nil {
				return err
			}
			name := filepath.ToSlash(rel)
			included := surface.label == "project" && (filepath.Base(path) == "AGENTS.md" || strings.HasPrefix(name, ".codex/") || strings.HasPrefix(name, ".opencode/"))
			included = included || surface.label == "home"
			if !included || entry.IsDir() {
				return nil
			}
			normalize := func(text string) string {
				return strings.ReplaceAll(strings.ReplaceAll(text, root, "{project}"), home, "{home}")
			}
			artifact := goldenArtifact{Kind: "file"}
			info, err := os.Lstat(path)
			if err != nil {
				return err
			}
			if info.Mode()&os.ModeSymlink != 0 {
				artifact.Kind = "link"
				target, err := os.Readlink(path)
				if err != nil {
					return err
				}
				artifact.Target = normalize(target)
			} else {
				raw, err := os.ReadFile(path)
				if err != nil {
					return err
				}
				artifact.Content = normalize(string(raw))
				artifact.Mode = uint32(info.Mode().Perm())
			}
			artifacts[surface.label+"/"+name] = artifact
			return nil
		}); err != nil {
			t.Fatal(err)
		}
	}
	return artifacts
}

func TestProjectGoldenFixtures(t *testing.T) {
	for _, name := range []string{"plain", "professor"} {
		t.Run(name, func(t *testing.T) {
			fixture := filepath.Join("..", "..", "testdata", "projects", name)
			jail := testjail.Scratch(t)
			root, home := filepath.Join(jail, "project"), filepath.Join(jail, "home")
			copyGoldenInput(t, filepath.Join(fixture, "input"), jail)
			variables := map[string]string{"HOME": home, "XDG_CONFIG_HOME": filepath.Join(home, ".config"), "XDG_STATE_HOME": filepath.Join(jail, "state"), "XDG_DATA_HOME": filepath.Join(home, ".local", "share"), "CLAUDE_PROJECT_DIR": root}
			e := env{get: func(key string) string { return variables[key] }}
			globalArgs := []string{"global"}
			if name == "professor" {
				globalArgs = append(globalArgs, "--source-repo", root)
			}
			for _, args := range [][]string{{"build", root}, {"check", root}, globalArgs} {
				var out, errOut bytes.Buffer
				if code := dispatch(args, &out, &errOut, e); code != 0 {
					t.Fatalf("%v rc=%d: %s%s", args, code, &out, &errOut)
				}
			}
			for _, surface := range []string{root, home} {
				if err := filepath.WalkDir(surface, func(path string, entry fs.DirEntry, err error) error {
					if err != nil {
						return err
					}
					if entry.IsDir() || entry.Type()&os.ModeSymlink != 0 {
						return nil
					}
					raw, err := os.ReadFile(path)
					if err != nil {
						return err
					}
					for _, legacy := range []string{"Generated by pfm", "Generated by .claude/scripts/"} {
						if bytes.Contains(raw, []byte(legacy)) && !(filepath.Base(path) == "config.toml" && legacy == "Generated by .claude/scripts/") {
							t.Errorf("generated file %s carries legacy marker %q", path, legacy)
						}
					}
					first, _, _ := strings.Cut(string(raw), "\n")
					if strings.Contains(first, "Generated by engine-sync") && !strings.Contains(first, "then run: engine-sync build") && !strings.Contains(first, "then run: engine-sync global") {
						t.Errorf("marker in %s does not carry its rebuild command", path)
					}
					return nil
				}); err != nil {
					t.Fatal(err)
				}
			}
			got := collectGoldenArtifacts(t, root, home)
			raw, err := os.ReadFile(filepath.Join(fixture, "golden", "artifacts.json"))
			if err != nil {
				t.Fatalf("golden fixture: %v", err)
			}
			var want map[string]goldenArtifact
			if err := json.Unmarshal(raw, &want); err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(got, want) {
				for path, artifact := range got {
					if !reflect.DeepEqual(artifact, want[path]) {
						t.Errorf("artifact %s:\ngot %#v\nwant %#v", path, artifact, want[path])
					}
				}
				for path := range want {
					if _, ok := got[path]; !ok {
						t.Errorf("missing artifact %s", path)
					}
				}
			}
			if name == "plain" {
				raw, err := json.Marshal(got)
				if err != nil {
					t.Fatal(err)
				}
				for _, term := range []string{"Professor", "professor", "pfm", "gitter", "guarded files", "LICENSE", "SECURITY.md"} {
					if bytes.Contains(raw, []byte(term)) {
						t.Errorf("plain golden contains %q", term)
					}
				}
			}
		})
	}
}

func TestAuditGoldenRecordsWholeHomeAndMarkers(t *testing.T) {
	root, home := testjail.Scratch(t), testjail.Scratch(t)
	marker := "<!-- Generated by engine-sync from agents/reader.md — edit the source, then run: engine-sync build -->\n"
	putProjectFile(t, home, "unexpected/output.md", marker+"Body\n")
	got := collectGoldenArtifacts(t, root, home)
	if got["home/unexpected/output.md"].Content != marker+"Body\n" {
		t.Fatalf("unobserved write or marker: %#v", got)
	}
}
