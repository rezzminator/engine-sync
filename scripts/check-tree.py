#!/usr/bin/env python3
"""Mechanical architecture gates. Baselines may only shrink."""
import argparse, collections, json, os, pathlib, re, subprocess, sys
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--root',type=pathlib.Path,default=pathlib.Path(__file__).resolve().parent.parent)
p.add_argument('--measure',action='store_true');p.add_argument('--only');p.add_argument('--binary',type=pathlib.Path)
a=p.parse_args();root=a.root.resolve();results={};error={}
ids=['size-src','size-test','size-cmd','negation-dirs','doc-go','test-mirror','testjail','dup-functions','facade-write','facade-env','facade-exec','facade-marker','facade-frontmatter','spelling-professor','spelling-states','registry-parity','orientation-truth','publication']
ids+=['spelling-variant']
if a.only and a.only not in ids:
 print('CHECK selection ERROR unknown check '+a.only);sys.exit(2)
for i in ids:results[i]=[]
try:
 enumeration=subprocess.run(['git','ls-files','-co','--exclude-standard','-z'],cwd=root,capture_output=True,timeout=30)
 if enumeration.returncode:raise ValueError('git ls-files failed: '+enumeration.stderr.decode(errors='replace').strip())
 listed=sorted({root/name for name in enumeration.stdout.decode().split('\0') if name and (root/name).is_file()})
 files=[f for f in listed if f.suffix=='.go' and f.relative_to(root).parts[0] in ['internal','cmd']]
except (OSError,UnicodeError,ValueError,subprocess.TimeoutExpired) as exc:
 print('CHECK '+(a.only or 'enumeration')+' ERROR '+str(exc));sys.exit(2)
try:texts={f:f.read_text() for f in files}
except (OSError,UnicodeError) as exc:
 print('CHECK '+(a.only or 'enumeration')+' ERROR '+str(exc));sys.exit(2)
if not files:
 print('CHECK '+(a.only or 'enumeration')+' ERROR empty source enumeration');sys.exit(2)
functions=collections.defaultdict(list);packages=collections.defaultdict(list)
allowpath=root/'scripts/marker-allowlist.txt'
try:allow=set(allowpath.read_text().splitlines()) if allowpath.exists() else set()
except (OSError,UnicodeError) as exc:print('CHECK '+(a.only or 'enumeration')+' ERROR '+str(exc));sys.exit(2)
for f,s in texts.items():
 path=f.relative_to(root).as_posix();test=f.name.endswith('_test.go');lines=s.splitlines();packages[f.parent].append(s)
 if len(lines)>(910 if test else 510):results['size-test' if test else 'size-src'].append(f'{path} {len(lines)}')
 for name in re.findall(r'^func ([A-Za-z_][A-Za-z0-9_]*)\(',s,re.M):
  if name not in ['main','init','TestMain']:functions[name.casefold()].append(path)
 if not test and f.name!='doc.go' and not f.with_name(f.stem+'_test.go').exists():results['test-mirror'].append(path)
 if test and '/testjail/' not in '/'+path and re.search(r'\b\w+\.TempDir\s*\(|os\.MkdirTemp\s*\(',s):results['testjail'].append(path)
 if test:continue
 # Comments do not invoke primitives. Strings are retained for marker/state gates.
 code=re.sub(r'(?m)^\s*//.*$','',s)
 checks={'facade-write':('/atomicfile/',r'os\.(?:WriteFile|Rename|Symlink)\b'),'facade-env':('/paths/',r'os\.(?:Getenv|LookupEnv|UserHomeDir|Environ|ExpandEnv|Setenv|Unsetenv|Clearenv)\b'),'facade-exec':('/paths/',r'exec\.Command(?:Context)?\b'),'facade-frontmatter':('/source/',r'(?i)func (?:parseFrontmatter|parseOpenCodeFrontmatter|frontmatterLines|normalizeFrontmatter|(?:parse|decode|read|split)[A-Za-z_]*frontmatter[A-Za-z_]*)\(')}
 for check,(module,pattern) in checks.items():
  if module not in '/'+path and not(check=='facade-env' and path=='internal/config/env.go') and not(check in ['facade-write','facade-env','facade-exec'] and path=='internal/testjail/testjail.go') and re.search(pattern,code):results[check].append(path)
 if '/artifact/' not in '/'+path and re.search(r'"[^"\n]*Generated by',code):results['facade-marker'].append(path)
 if '/reconcile/' not in '/'+path and re.search(r'"(?:MISSING|STALE|ORPHAN|CONFLICT|UNPARSEABLE|INVALID|DANGLING|KEPT)(?:"| )',code):results['spelling-states'].append(path)
 for line in lines:
  if re.search(r'professor|pfm|gitter|\.professor|template[s]/global/|First actio[n]: read the repository root|Review the uncommitted changes only in your task.s own files',line,re.I) and path+'\t'+line not in allow:results['spelling-professor'].append(path);break
# The published verb's home is exempt; string literals are never scanned.
variant_home={'internal/cli/variants.go','internal/cli/variants_test.go'}
variant_paths=set()
for f in listed:
 rel=f.relative_to(root);path=rel.as_posix()
 if rel.parts[0] not in ['internal','cmd','testdata'] or path in variant_home:continue
 for depth in range(1,len(rel.parts)+1):
  if re.search('variant',rel.parts[depth-1],re.I):variant_paths.add('/'.join(rel.parts[:depth]))
results['spelling-variant'].extend(sorted(variant_paths))
for f,s in texts.items():
 path=f.relative_to(root).as_posix()
 if path in variant_home:continue
 for line in s.splitlines():
  if re.search(r'^(func|type|var|const)\s+(\([^)]*\)\s*)?\w*[Vv]ariant',line):results['spelling-variant'].append(path+': '+line)
for name,paths in functions.items():
 if len(paths)>1:results['dup-functions'].append(name+' '+','.join(paths))
count=sum(len(s.splitlines()) for f,s in texts.items() if f.parent in [root/'cmd/engine-sync',root/'internal/cli'] and not f.name.endswith('_test.go'))
if count>900:results['size-cmd']=[str(count)]
for directory,entries in packages.items():
 if not any(re.search(r'// Package \w+',s) for s in entries):results['doc-go'].append(directory.relative_to(root).as_posix())
for f in {parent for file in listed for parent in file.parents if root in parent.parents}:
 if re.fullmatch(r'util.*|helpers|common|misc|shared',f.name):results['negation-dirs'].append(f.relative_to(root).as_posix())
# Scan the tracked and untracked text surface; compatibility literals and
# attribution have exact path-and-line exceptions, never directory exemptions.
standalone=re.compile(r'\b(?:professor|pfm|gitter|flight|fleet|framework)\b|dispatch prompt|workbench\.json|templates/global|First action: read the repository root',re.I)
for f in listed:
 path=f.relative_to(root).as_posix()
 if path.startswith('testdata/projects/professor/') or path=='scripts/marker-allowlist.txt':continue
 try:
  raw=f.read_bytes()
  if b'\0' in raw:continue
  content=raw.decode('utf-8')
 except (OSError,UnicodeError) as exc:error['spelling-professor']=str(exc);continue
 for line in content.splitlines():
  if standalone.search(line) and path+'\t'+line not in allow:
   results['spelling-professor'].append(path);break
wrapper=root/'plugins/engine-sync/libexec/engine-sync'
# One command table and one target registry feed dispatch, usage and the contract.
main=root/'internal/cli/main.go'
if main.exists():
 commands=set(re.findall(r'\{"(\w+)",',texts[main]))
 if not commands:error['registry-parity']='empty command enumeration'
 for doc in ['README.md','docs/interface.md']:
  f=root/doc
  if not f.exists():results['registry-parity'].append(doc+' missing');continue
  section=f.read_text().split('## Commands\n',1)[-1].split('\n## ',1)[0]
  documented=set(re.findall(r'^\| `(\w+)`',section,re.M))
  if commands!=documented:results['registry-parity'].append(doc+' commands '+str(sorted(commands^documented)))
# Every internal package directory holding Go is documented, and every documented package exists.
architecture=root/'docs/architecture.md'
package_dirs={f.parent.relative_to(root/'internal').as_posix() for f in files if f.relative_to(root).parts[0]=='internal' and f.parent!=root/'internal'}
try:
 if not architecture.exists():results['registry-parity'].append('docs/architecture.md missing')
 else:
  table=architecture.read_text().split('## Package responsibilities',1)
  if len(table)==1:results['registry-parity'].append('docs/architecture.md lacks § Package responsibilities')
  else:
   documented=set()
   for row in table[1].split('\n## ',1)[0].splitlines():
    cell=row.split('|')[1].strip() if row.startswith('|') and row.count('|')>2 else ''
    if cell in ['','Package'] or re.fullmatch(r'[-: ]+',cell):continue
    documented.update(name.strip().strip('`') for name in cell.split(','))
   results['registry-parity'].extend('docs/architecture.md lacks internal/'+name for name in sorted(package_dirs-documented))
   results['registry-parity'].extend('docs/architecture.md names absent internal/'+name for name in sorted(documented) if not (root/'internal'/name).is_dir())
except (OSError,UnicodeError) as exc:error['registry-parity']='architecture producer: '+str(exc)
version_path=root/'plugins/engine-sync/.claude-plugin/plugin.json'
if main.exists() and version_path.exists():
 try:
  declared=re.findall(r'^var Version = "([^"]+)"',main.read_text(),re.M)
  release=json.loads(version_path.read_text())['version']
  def version_core(value):
   match=re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:-([0-9A-Za-z.-]+))?(?:\+([0-9A-Za-z.-]+))?',value)
   if not match:raise ValueError('invalid version '+str(value))
   return tuple(map(int,match.group(1,2,3))),match.group(4)
  dev,pre=version_core(declared[0]) if len(declared)==1 else (_ for _ in ()).throw(ValueError('cli.Version must have one declaration'))
  stable,_=version_core(release)
  if not pre or dev<=stable:results['registry-parity'].append('cli.Version must be a prerelease strictly newer than manifest '+release)
 except (OSError,UnicodeError,ValueError,KeyError,IndexError) as exc:error['registry-parity']='version producer: '+str(exc)
else:error['registry-parity']='version producer or plugin manifest missing'
if a.only is None or a.only=='registry-parity':
 try:
  cmd=[str(a.binary.resolve()),'config','schema'] if a.binary else ['go','run','./cmd/engine-sync','config','schema']
  actual=subprocess.run(cmd,cwd=root,capture_output=True,timeout=120)
  if actual.returncode: error['registry-parity']='schema producer failed'
  elif actual.stdout!=(root/'docs/engine-sync.schema.json').read_bytes():results['registry-parity'].append('docs/engine-sync.schema.json drift')
 except (OSError,subprocess.TimeoutExpired) as e:error['registry-parity']=str(e)
# Check literal repository pointers and declared engine-sync variables.
for f in [root/'CLAUDE.md',root/'README.md',root/'plugins/engine-sync/README.md']+list((root/'docs').glob('*.md')):
 if not f.exists():continue
 try:s=f.read_text()
 except (OSError,UnicodeError) as exc:error['orientation-truth']=str(exc);continue
 for pointer in re.findall(r'(?m)(?:`|^\s*)((?:internal|cmd|scripts|testdata|docs|plugins|\.github|\.claude-plugin)/[^`\s*{}]+)(?:`|\s*$)',s):
  pointer=pointer.rstrip('.,:');pointer=re.sub(r':\d+$','',pointer)
  if not (root/pointer).exists():results['orientation-truth'].append(f.name+' '+pointer)
 for name in set(re.findall(r'\bENGINE_SYNC_[A-Z_]+\b',s)):
  implementation='\n'.join(s for f,s in texts.items() if not f.name.endswith('_test.go') and 'testjail' not in f.parts)+'\n'.join(f.read_text() for f in (root/'plugins/engine-sync').glob('**/*.sh'))+(wrapper.read_text() if wrapper.exists() else '')
  if name not in implementation:results['orientation-truth'].append(f.name+' '+name)
gap={}
if a.only is None or a.only=='publication':
 # The terms are private and untracked: LEAK_TERMS, else scripts/leak-terms.txt as leak-check.sh reads it.
 terms=os.environ.get('LEAK_TERMS')
 try:
  if not terms and (root/'scripts/leak-terms.txt').is_file():terms=str(root/'scripts/leak-terms.txt')
  if not terms:gap['publication']='LEAK_TERMS not supplied (private terms: trusted runs supply them); no leak scan ran'
  else:
   if not pathlib.Path(terms).is_file():raise ValueError('LEAK_TERMS file required')
   if not any(line.strip() and not line.lstrip().startswith(('#','!ignore-token')) for line in pathlib.Path(terms).read_text().splitlines()):raise ValueError('LEAK_TERMS has zero usable terms')
   process=subprocess.run(['bash','scripts/leak-check.sh'],cwd=root,env=dict(os.environ,LEAK_TERMS=terms),capture_output=True,text=True,timeout=120)
   output=process.stdout+process.stderr
   scanned=re.findall(r'[^\n]*(?:scanned|files)[^\n]*',output);publication_note='; '.join(scanned[-2:])
   if process.returncode:
    if re.search(r'FAILED.*[1-9][0-9]* hit',output):results['publication']=[output.strip()]
    else:error['publication']='leak producer failed: '+output.strip()
   elif not re.search(r'[1-9][0-9]* (?:file|files)|scanned[^\n]*[1-9][0-9]*',output):error['publication']='empty or missing leak enumeration'
 except (OSError,UnicodeError,ValueError,subprocess.TimeoutExpired) as exc:error['publication']=str(exc)
# Compare changed baselines with the trusted Git base, including in CI.
base_ref=os.environ.get('CHECK_TREE_BASE_REF','HEAD')
try:
 top=subprocess.run(['git','rev-parse','--show-toplevel'],cwd=root,capture_output=True,text=True,timeout=10)
 compare=top.returncode==0 and pathlib.Path(top.stdout.strip()).resolve()==root
 if os.environ.get('CHECK_TREE_BASE_REF') and not compare:raise ValueError('cannot compare baseline base '+base_ref)
except (OSError,ValueError,subprocess.TimeoutExpired) as exc:compare=False;error[a.only or 'registry-parity']=str(exc)

rc=0;ran=collections.Counter()
for i in ids:
 if a.only and a.only!=i:continue
 baseline=root/'scripts/baselines'/f'{i}.txt'
 if not baseline.exists():error[i]='baseline missing'
 else:
  try:old=set(baseline.read_text().splitlines())
  except (OSError,UnicodeError) as exc:error[i]=str(exc);old=set()
  if compare:
   try:
    path='scripts/baselines/'+i+'.txt'
    entry=subprocess.run(['git','ls-tree',base_ref,'--',path],cwd=root,capture_output=True,text=True,timeout=10)
    trusted=subprocess.run(['git','show',base_ref+':'+path],cwd=root,capture_output=True,text=True,timeout=10) if entry.returncode==0 and entry.stdout.strip() else entry
   except (OSError,UnicodeError,subprocess.TimeoutExpired) as exc:print('CHECK '+i+' ERROR trusted baseline producer: '+str(exc));sys.exit(2)
   if trusted.returncode:error[i]='trusted baseline producer failed: '+base_ref+': '+trusted.stderr.strip()
   trusted_rows=set(trusted.stdout.splitlines())
   if trusted.returncode==0 and not i.startswith('size-') and old-trusted_rows:error[i]='baseline growth against '+base_ref+': '+', '.join(sorted(old-trusted_rows))
   if trusted.returncode==0 and i.startswith('size-'):
    try:
     def row_count(row):
      if ' ' in row: key,n=row.rsplit(' ',1);return key,int(n)
      return i,int(row)
     prior=dict(row_count(row) for row in trusted_rows)
     if any(row_count(row)[1]>prior.get(row_count(row)[0],0) for row in old):error[i]='size baseline growth against '+base_ref
    except ValueError as exc:error[i]='malformed size baseline: '+str(exc)
  current=set(results[i]);new=current-old
  if i.startswith('size-'):
   def measured(row):
    if ' ' in row:
     key,count=row.rsplit(' ',1);return key,int(count)
    return i,int(row)
   try:
    ceiling=dict(measured(row) for row in old)
    new={row for row in current if measured(row)[1]>ceiling.get(measured(row)[0],0)}
   except ValueError as exc:error[i]='malformed size baseline: '+str(exc)
  if a.measure:
   if new:error[i]='measure refuses growth: '+', '.join(sorted(new))
   elif i not in error and i not in gap:baseline.write_text(''.join(v+'\n' for v in sorted(current)))
  results[i]=sorted(new)
 if i in error:print(f'CHECK {i} ERROR {error[i]}');rc=2;ran['ERROR']+=1
 elif results[i]:print(f'CHECK {i} FAIL '+ '; '.join(results[i]));rc=max(rc,1);ran['FAIL']+=1
 elif i in gap:print(f'CHECK {i} GAP {gap[i]}')
 else:print(f'CHECK {i} PASS'+(' '+publication_note if i=='publication' else ''));ran['PASS']+=1
# A gap is no pass and no red: it decides the exit code (3) only when every check that ran passed.
# A gapped check that still ended in ERROR ran, so it is counted there and never also as not run.
gap={i:why for i,why in gap.items() if i not in error}
if gap:print(f"CHECK TREE GAP — not run: {', '.join(sorted(gap))} · ran {sum(ran.values())}: {ran['PASS']} PASS, {ran['FAIL']} FAIL, {ran['ERROR']} ERROR")
sys.exit(rc or (3 if gap else 0))
